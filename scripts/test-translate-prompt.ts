/**
 * 翻译提示词里的**产品口径**回归（离线，不联网、不调模型）。
 *
 * 用法：`pnpm test:translate-prompt`
 *
 * ## 为什么必须有这个脚本
 *
 * `translate.ts` 的 `TRANSLATE_PROMPT` 里装着两条**产品口径**：
 *
 * 1. **「投资者相关」的题材范围** = 政经 / 外资 / 工商税法 / 行业项目 / 社会民生。
 * 2. **专有名词写法**：人名（分两类：国家领导人/国际名人 → 中文；其余 → 拉丁）/ 公司名 /
 *    机构名 / 项目名 → 拉丁字母；**国名 / 州（自治共和国）/ 城市 → 中文**。
 * 3. **标题必须以原标题为底本忠实翻译**，不许拿正文里的另一组数字顶替。
 *
 * 这三条**不在类型系统里**，也没有任何编译期检查 —— 提示词是一整块字符串，
 * 「顺手精简一下」就能把它们删掉，而症状要几天后才以
 * 「怎么没有民生新闻了」「人名怎么又译回中文了」「同一件事怎么像三条新闻」的形式出现。
 *
 * ## 口径 2 的演变（**改之前先读，这一条改过三次**）
 *
 * - **第一版**（至 2026-09-23）：**只**人名拉丁，且明写「机构名、公司名、地名、职务照常译成中文」。
 *   实测这条在生产里基本没被遵守，且**两种写法并存是主流**：
 *   7 天 × 5 国 1757 篇里 Aliyev 中文 57 篇 / 拉丁 22 篇、Japarov 36/12、Tokayev 23/14，
 *   其中分别有 4 / 3 / 2 篇**同一篇里两种都出现**；另有 3.2% 的篇目含
 *   `米尔зиёё夫`／`肯еш` 这种「汉字 + 西里尔」挤在一个词里的写法。
 * - **第二版**（当天中途）：一度定成「专有名词（含国名地名）**一律拉丁**」。
 * - **第三版**（2026-09-23 定稿）：用户随即收窄为
 *   「**国名和州名这类国内已经通用的专有名词还是用中文**」⇒ 拉丁只给人名与公司/机构名。
 * - **第四版 = 当前定稿**（2026-09-28）：用户看完 `卡赫拉莫恩·库罗诺Boyev` 后要求
 *   「只要不是国名、州名、**总统或名人的名字**、以及国内已明显有约定俗成译名的，
 *   都统一使用英文字母」⇒ **人名拆成两类**：国家领导人 + 国际知名人物 → 中文；
 *   其余所有人名 → 拉丁。并明令禁止「一个名字译一半」的混合体。
 *   实测范围（2026-09-28，500 篇）：含「汉字·汉字」音译人名的有 **50 篇（10%）**，
 *   其中约一半是国家领导人/国际名人（**按新口径本来就该是中文**），
 *   另一半（`阿伊道斯·米尔扎赫梅托夫`、`布尔哈内丁·杜兰`…）必须改成拉丁。
 *
 * ⚠️ 前三版的句子**都不许回来**，下面各有专门的反向断言盯着
 * （`只针对人名` / `照常译成中文` / `一律保留拉丁字母` 三个字符串都不许出现在提示词里）。
 *
 * 已经踩过一次：旧口径的正向清单是
 * 「经济形势、行业发展、能源/矿产/基建/制造业项目、外贸与投资协议、金融与汇率、
 * 国家政策法规、政局变动、影响营商环境的社会治安事件」，
 * **社会民生整类不在里面**，而负向清单里的「日常生活琐事」又很容易把它一起扫掉 ——
 * 于是物价、工资、补贴、税费这类**没有金额但直接决定消费能力与劳动力成本**的稿子
 * 在入库阶段就没了。所以下面有两条断言专门盯这件事：
 * 「五类正向题词都在」+「旧的『宁可从严』不许回来」。
 *
 * ## 为什么断言的是「句子在不在」而不是「模型判得对不对」
 *
 * 模型判得对不对要靠 `scripts/test-translate.ts`（真调模型，联网、要 Key）。
 * 本脚本管的是**更前面一层**：口径有没有被写进提示词。两层都要，
 * 因为「口径没写进去」和「写进去了但模型不听」是两种不同的故障，
 * 混在一起查会查错方向。
 */
import { TRANSLATE_PROMPT, langLabel, CATEGORY_IDS, buildRepairHint, buildPrompt } from '../src/lib/translate';
