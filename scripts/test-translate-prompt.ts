// Tashkent 被排除在外（第 6 条拿它当反例）；Kazakhstan 同理，所以不做全量断言。
for (const en of ['Astana', 'Almaty', 'Bishkek', 'Dushanbe', 'Baku', 'Khujand']) {
  ok(`提示词里没有英文城市名 ${en}`, !P.includes(en));
}

