// 每种**源清单里声明过的语言**都要有像样的语言名。
// 漏一种 → 模型收到「其他语言」，等于没告诉它原文是什么语言。
{
  const langs = [...new Set(RSS_SOURCES.map((s) => s.language))].sort();
  for (const lang of langs) {
    const label = langLabel(lang);
    ok(
      `langLabel('${lang}') 有具体语言名（不是「其他语言」）`,
      label !== '其他语言',
      `得到「${label}」；源清单里新增了语言就要在 langLabel 里补上`,
    );
  }
}

// 民生必须真的是一个可选分类 —— 提示词让它「一律 true」，
// 但如果没有对应的 category id，模型只能硬塞进别的类里。
ok(
  '分类枚举里有 livelihood（民生）',
  (CATEGORY_IDS as string[]).includes('livelihood'),
  CATEGORY_IDS.join(', '),
);

// 提示词里不该泄漏「你是提示词/规则」这类元信息（模型会照抄进正文）
ok(
  '没有把「忽略以上指令」之类的注入痕迹留在正文要求里',
  !/忽略(以上|上面)指令/.test(P),
);

// ============================================================
// 质检失败后的「重试修正指令」
// ============================================================

/**
 * `buildRepairHint` 是**闸门的配套护栏**，不是可有可无的文案。
 *
 * 背景：`translateNews` 的三次重试**用的是同一个提示词**，而「专名译了一半」（`阿克tau市`）
 * 是模型的**系统性**转写习惯，不是随机手滑。三次不过该篇就被丢弃
 * （返回 `translated:false`、调用方不入库）⇒ **静默丢稿**。
 * 这段指令把「上一次错在哪、该改成什么」告诉模型，才有机会在第二次就修好。
 *
 * ⇒ 断言的目的不是文案好看，而是**防止它被删掉或退化成没有信息的空串**：
 *   一旦它没了，闸门就从「拦下 → 引导改正」变成「拦下 → 盲目重采样 → 丢稿」。
 */
section('质检失败后的重试修正指令（buildRepairHint）');

const hintHalf = buildRepairHint({ kind: 'half-translated', tokens: ['斯皮塔梅en区', '阿克tau市'] });
ok('半译专名的指令里带上了被拦下的词', hintHalf.includes('斯皮塔梅en区') && hintHalf.includes('阿克tau市'));
ok('半译专名的指令说清了原因（汉字后面残留拉丁）', hintHalf.includes('汉字后面残留'));
ok('指令给出了「要么完整中文、要么完整拉丁」的明确要求', /完整的中文译名/.test(hintHalf) && /完整的拉丁写法/.test(hintHalf));
ok('指令里带具体改法示例（阿克tau市 → 阿克套市）', hintHalf.includes('阿克套市'));
ok(
  '指令里明确「不要把这些要求写进 content」（否则模型会把说明抄进正文）',
  hintHalf.includes('不要写进 content'),
);

const hintMixed = buildRepairHint({ kind: 'mixed-script', tokens: ['米尔зиёё夫'] });
ok('汉字+西里尔那类的指令换了一套说法', hintMixed.includes('西里尔') && !hintMixed.includes('汉字后面残留'));
ok('两类原因的指令互不相同（不是同一段文案复用）', hintHalf !== hintMixed);

// ------------------------------------------------------------
// 「拉丁+西里尔」同词（2026-09-29 进闸）：**必须有自己的措辞与示例**
// ------------------------------------------------------------
//
// ⚠️ 这一类命中的词里**一个汉字都没有**（`Kaрабалиева`／`MЧС`／`TОО`）。
// 如果它落进上面那个二元判断的 else 分支，会拿到「汉字与西里尔字母挤在同一个词里」
// 的说明和「斯皮塔梅en区 → Spitamen 区」的示例 —— 对着一个没有汉字的词讲汉字，
// 是**答非所问**，而重试只有一次机会（三次不过即丢稿）。
const hintLatinCyr = buildRepairHint({ kind: 'latin-cyrillic', tokens: ['Kaрабалиева', 'MЧС'] });
ok(
  '拉丁+西里尔类的指令带上了被拦下的词',
  hintLatinCyr.includes('Kaрабалиева') && hintLatinCyr.includes('MЧС'),
);
ok(
  '拉丁+西里尔类说清了原因（一个词里混了两种字母）',
  hintLatinCyr.includes('拉丁字母和西里尔字母'),
);
ok(
  '拉丁+西里尔类给的是**同类**示例（Qarabaliyeva / Myrzakhmetov）',
  hintLatinCyr.includes('Qarabaliyeva') && hintLatinCyr.includes('Myrzakhmetov'),
);
ok(
  '★ 拉丁+西里尔类**不许**套用「汉字 + 字母」那套措辞（答非所问）',
  !hintLatinCyr.includes('汉字 + 字母') && !hintLatinCyr.includes('斯皮塔梅en区'),
  '命中的词里没有汉字，讲「汉字+字母」模型会不知道在说哪个词',
);
ok('拉丁+西里尔类同样声明「不要写进 content」', hintLatinCyr.includes('不要写进 content'));
ok(
  '三类原因的指令互不相同（不是同一段文案复用）',
  hintHalf !== hintMixed && hintMixed !== hintLatinCyr && hintHalf !== hintLatinCyr,
);

// 被拦下的词可能很多，指令不能无限膨胀（提示词长度有成本）
const hintLong = buildRepairHint({
  kind: 'half-translated',
  tokens: Array.from({ length: 30 }, (_, i) => `专名${i}en`),
});
ok('被拦词很多时指令有上限（最多列 8 个）', hintLong.includes('专名7en') && !hintLong.includes('专名8en'));

// ------------------------------------------------------------
// 倍数类（2026-09-29 新增）：提示词第 7 条 + 闸的修正指令块
// ------------------------------------------------------------
//
// 用户 2026-09-28 报「电价下调1.5倍」这类「数字对、话不通」的错。
// 两类承载体都要钉：提示词（预防）+ 闸的修正指令（补救）。
// 只钉一个的话，另一处被删掉不会有任何症状，只会继续出病句。

// 提示词第 7 条：方向规则必须写进去
ok('提示词有第 7 条（数字、单位与倍数）', TRANSLATE_PROMPT.includes('数字、单位与倍数'));
ok(
  '第 7 条写明了「倍只能用于增长、不能用于下降」',
  TRANSLATE_PROMPT.includes('只能用于增长') && TRANSLATE_PROMPT.includes('不能用于下降'),
);
ok(
  '第 7 条给了俄语两种来源写法（в N раза / понижающий коэффициент）',
  TRANSLATE_PROMPT.includes('в 1.5 раза') && TRANSLATE_PROMPT.includes('коэффициент'),
);
ok(
  '第 7 条要求「出现系数必须说清是乘还是除」（只写系数读者判不出涨跌）',
  TRANSLATE_PROMPT.includes('说清它是**乘**还是**除**'),
);
ok(
  '第 7 条带了用户报的那条反例（下调 1.5 倍 ⇒ 降至原来的 1/1.5）',
  TRANSLATE_PROMPT.includes('下调 1.5 倍') && TRANSLATE_PROMPT.includes('1/1.5'),
);
// 量词那一段（500 座教学楼）
ok('第 7 条写明了量词必须来自「数字实际修饰的名词」', TRANSLATE_PROMPT.includes('量词必须来自'));
ok(
  '第 7 条带了 500 мест 的反例（座位/名额 ≠ 栋楼）',
  TRANSLATE_PROMPT.includes('мест') && TRANSLATE_PROMPT.includes('500 个学生名额'),
);
ok(
  '第 7 条要求「拿不准时把单位写全」而不是写一个语义不清的量词',
  TRANSLATE_PROMPT.includes('把单位写全'),
);
ok('第 7 条规范了 № 的写法（写成「第」）', TRANSLATE_PROMPT.includes('№13') && TRANSLATE_PROMPT.includes('第 13'));

// 修正指令里必须有倍数那一块 —— 而且要**讲清该改成什么**。
// 只叫模型「重写一遍」是没用的：它不是手滑，是在直译 в N раза。
const hintMult = buildRepairHint({ kind: 'impossible-multiple', tokens: [], impossibleMultiples: ['下调1.5倍'] });
ok('倍数类的修正指令带上了被拦下的说法', hintMult.includes('下调1.5倍'));
ok('倍数类的修正指令讲明「下降 N 倍 在中文里逻辑不成立」', hintMult.includes('逻辑不成立'));
ok('倍数类的修正指令讲明原文的语义是「除以」', hintMult.includes('除以'));
ok('倍数类的修正指令给了可直接照抄的正确说法（1/1.5）', hintMult.includes('1/1.5'));
ok('倍数类的修正指令提醒「增长方向仍可用倍」（不要一并改错）', hintMult.includes('增长'));
ok('倍数类的修正指令同样声明「不要写进 content」', hintMult.includes('不要写进 content'));

// 两类问题同时出现时，**一次说清**（重试只有一次机会，只说一类会撑到丢稿）
const hintBoth = buildRepairHint({
  kind: 'half-translated',
  tokens: ['阿克tau市'],
  impossibleMultiples: ['下调1.5倍'],
});
ok(
  '两类问题同时命中时，修正指令两块都带（不是二选一）',
  hintBoth.includes('阿克tau市') && hintBoth.includes('下调1.5倍'),
);

// 空 reject（理论上的兜底）不得吐出一段没有信息的文案
ok('没有任何问题时指令为空串（不是一段空话）', buildRepairHint({ kind: 'half-translated', tokens: [] }) === '');

