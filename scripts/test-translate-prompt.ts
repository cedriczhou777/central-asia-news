/**
 * 翻译提示词里的**产品口径**回归（离线，不联网、不调模型）。
 *
 * 用法：`pnpm test:translate-prompt`
 *
 * ## 为什么必须有这个脚本
 *
 * `translate.ts` 的 `TRANSLATE_PROMPT` 里装着两条**产品口径**：
 *
 * 1. **「投资者相关」的题材范围** = 政经 / 外资 / 工商税法 / 行业项目 / 社会民生。
 * 2. **专有名词写法**：人名 / 公司名 / 机构名 / 项目名 → 拉丁字母；
 *    **国名 / 州（自治共和国）/ 城市 → 中文**。
 * 3. **标题必须以原标题为底本忠实翻译**，不许拿正文里的另一组数字顶替。
 *
 * 这三条**不在类型系统里**，也没有任何编译期检查 —— 提示词是一整块字符串，
 * 「顺手精简一下」就能把它们删掉，而症状要几天后才以
 * 「怎么没有民生新闻了」「人名怎么又译回中文了」「同一件事怎么像三条新闻」的形式出现。
 *
 * ## 口径 2 的演变（**改之前先读，这一条改过两次**）
 *
 * - **第一版**（至 2026-09-23）：**只**人名拉丁，且明写「机构名、公司名、地名、职务照常译成中文」。
 *   实测这条在生产里基本没被遵守，且**两种写法并存是主流**：
 *   7 天 × 5 国 1757 篇里 Aliyev 中文 57 篇 / 拉丁 22 篇、Japarov 36/12、Tokayev 23/14，
 *   其中分别有 4 / 3 / 2 篇**同一篇里两种都出现**；另有 3.2% 的篇目含
 *   `米尔зиёё夫`／`肯еш` 这种「汉字 + 西里尔」挤在一个词里的写法。
 * - **第二版**（当天中途）：一度定成「专有名词（含国名地名）**一律拉丁**」。
 * - **第三版 = 当前定稿**：用户随即收窄为
 *   「**国名和州名这类国内已经通用的专有名词还是用中文**」⇒ 拉丁只给人名与公司/机构名。
 *
 * ⚠️ 前两版的句子**都不许回来**，下面各有专门的反向断言盯着
 * （`只针对人名` / `照常译成中文` / `一律保留拉丁字母` 三个字符串都不许出现在提示词里）。
 *
 * 已经踩过一次：旧口径的正向清单是
 * 「经济形势、行业发展、能源/矿产/基建/制造业项目、外贸与投资协议、金融与汇率、
 * 国家政策法规、政局变动、影响营商环境的社会治安事件」，
 * **社会民生整类不在里面**，而负向清单里的「日常生活琐事」又很容易把它一起扫掉 ——
 * 于是物价、工资、补贴、税费这类**没有金额但直接决定消费能力与劳动力成本**的稿子
 * 在入库阶段就没了。所以下面有两条断言专门盯这件事：
 * 「五类正向题词都在」+「旧的『宁可从严』不许回来」。
 *
 * ## 为什么断言的是「句子在不在」而不是「模型判得对不对」
 *
 * 模型判得对不对要靠 `scripts/test-translate.ts`（真调模型，联网、要 Key）。
 * 本脚本管的是**更前面一层**：口径有没有被写进提示词。两层都要，
 * 因为「口径没写进去」和「写进去了但模型不听」是两种不同的故障，
 * 混在一起查会查错方向。
 */
import { TRANSLATE_PROMPT, langLabel, CATEGORY_IDS } from '../src/lib/translate';
import { RSS_SOURCES } from '../src/lib/data/rss-sources';

// ----- 极简断言（与其它 scripts/test-*.ts 同款，便于一起读输出）-----

let passed = 0;
const failures: string[] = [];

function ok(name: string, cond: boolean, detail = '') {
  if (cond) {
    passed++;
    console.log(`  ✓ ${name}`);
  } else {
    failures.push(`${name}${detail ? ` —— ${detail}` : ''}`);
    console.log(`  ✗ ${name}${detail ? ` —— ${detail}` : ''}`);
  }
}

function section(title: string) {
  console.log(`\n${'─'.repeat(64)}\n${title}\n`);
}

const P = TRANSLATE_PROMPT;

// ============================================================
// 一、相关性口径：正向清单必须完整包含五类
// ============================================================

section('一、相关性口径（正向清单五类）');

// 这五个词就是产品口径本身。少一个就说明有人改了范围。
for (const label of ['政经', '外资', '工商税法', '行业项目', '社会民生']) {
  ok(`正向清单含「${label}」`, P.includes(label));
}

// 光有「社会民生」这个标题不够 —— 要真的把具体题材列出来，
// 否则模型看到这四个字仍然不知道该不该放行物价稿。
for (const topic of ['物价', '工资', '就业', '补贴', '税费', '住房']) {
  ok(`社会民生列了具体题材「${topic}」`, P.includes(topic));
}

// ★ 回归点：正是这两句让民生稿子被扫掉。它们不许回来。
ok(
  '旧的「宁可从严」总则已移除（它会把正向清单里的题材一起压掉）',
  !P.includes('宁可从严'),
  '提示词里又出现「宁可从严」——除非确认要收紧，否则这是回归',
);
ok(
  '保留了「不要因为看起来不像投资新闻就判 false」的告诫',
  P.includes('不要因为') && P.includes('判 false'),
  '没有这条，模型会按「像不像投资新闻」的直觉把民生/税制类稿子判掉',
);

// 负向清单要还在（只加正向、不写负向 = 文体娱乐会涌进来）
ok('负向清单仍在（文体娱乐 / 生活方式 / 风俗礼节 / 社会琐事）',
  P.includes('文体娱乐') && P.includes('生活方式') && P.includes('风俗礼节'));

// ============================================================
// 一之二、标题忠实度：必须以原标题为底本
// ============================================================

section('一之二、标题忠实度（不许另凑标题）');

// 这是 2026-09-23 修的「同一件事看起来像三条新闻」的根因之一：
// 模型会从正文里另凑一个标题，把原标题的 223 换成正文的「10 起 / 50 部」。
ok(
  '要求标题以「原始标题」为底本忠实翻译',
  P.includes('原始标题') && P.includes('忠实翻译'),
  '缺这条模型会从正文另凑标题，同一件事在成品里看起来像几条不同新闻',
);
ok(
  '明说保留原标题的主语与关键数字',
  P.includes('保留原标题的主语') || (P.includes('保留原标题') && P.includes('关键数字')),
);
ok(
  '明说禁止拿正文里的另一组数字顶替',
  P.includes('顶替') || P.includes('另一组数字'),
);

// ============================================================
// 二、专有名词写法：人名/公司名拉丁，国名/州名/城市中文
// ============================================================

section('二、专有名词写法（人名公司名拉丁；国名州名中文）');

ok('人名要求拉丁字母', P.includes('人名') && P.includes('拉丁字母'));
ok('明说人名不要音译成汉字', P.includes('不要') && P.includes('音译成汉字'));

// 人名要具体给转写示例，否则模型不知道「通行英文转写」长什么样
ok('给了人名转写示例 Tokayev', P.includes('Tokayev'));
ok('给了人名转写示例 Mirziyoyev / Japarov', P.includes('Mirziyoyev') && P.includes('Japarov'));

// 公司/机构名要 Latin，且给的是「通行拉丁名」而不是新造的翻译
ok('公司/机构名要求拉丁', P.includes('公司名') && P.includes('机构名'));
ok(
  '给了公司/机构拉丁名示例（Kazakhmys / AIIB）',
  P.includes('Kazakhmys') && P.includes('AIIB'),
);
ok(
  '给了「原本就通行的拉丁名原样保留」的清单',
  P.includes('KEGOC') && P.includes('SOCAR'),
  '缺了这条，KEGOC/SOCAR 这类会被翻回中文',
);

// ★ 国名 / 州名 / 城市必须继续中文 —— 这是用户 2026-09-23 明确的收窄
section('二之二、★ 国名 / 州名 / 城市必须继续用中文');
ok('明说国名用中文', P.includes('国名') && P.includes('中文'));
ok(
  '点名禁止把国名写成英文',
  P.includes('不要') && P.includes('Kazakhstan') && P.includes('英文'),
  '缺这条模型会把 哈萨克斯坦 写成 Kazakhstan',
);
for (const cn of ['哈萨克斯坦', '乌兹别克斯坦', '吉尔吉斯斯坦', '塔吉克斯坦', '阿塞拜疆', '土库曼斯坦']) {
  ok(`国名清单含「${cn}」`, P.includes(cn));
}
ok(
  '明说州 / 自治共和国用中文',
  P.includes('自治共和国') && P.includes('一级行政区'),
);
ok('给了州名中文示例（东哈萨克斯坦州 / 曼格斯套州）',
  P.includes('东哈萨克斯坦州') && P.includes('曼格斯套州'));
ok('明说城市用中文', P.includes('城市') && P.includes('中文'));
ok('给了城市中文示例（阿斯塔纳 / 塔什干 / 杜尚别）',
  P.includes('阿斯塔纳') && P.includes('塔什干') && P.includes('杜尚别'));

// ★ 反向断言：两次旧口径都不许回来
ok(
  '旧的「只针对人名」限定未回来',
  !P.includes('只针对人名'),
  '出现「只针对人名」= 口径被改回第一版',
);
ok(
  '旧的「机构名、公司名、地名照常译成中文」未回来',
  !P.includes('照常译成中文'),
  '出现「照常译成中文」= 口径被改回第一版',
);
ok(
  '没有「专有名词（含国名地名）一律拉丁」那版口径的残留',
  !P.includes('一律保留拉丁字母'),
  '出现「一律保留拉丁字母」= 口径被改回第二版（全拉丁），国名会变英文',
);

// 通名仍中文 —— 少了这条，模型会把 President / Parliament 也写成英文
ok(
  '明确要求「职务与机构通名用中文」',
  P.includes('通名') && P.includes('中文'),
);
ok(
  '点名禁止把通名翻成英文单词',
  P.includes('President') && P.includes('Parliament'),
  '缺这条模型可能写「哈萨克斯坦 President Tokayev 在 Parliament 表示」这种半英半中',
);
ok(
  '要求同一实体全篇写法统一',
  P.includes('只能有一种写法'),
  '缺这条会出现「托卡耶夫」和 Tokayev 同时出现在一篇里（实测 4 篇）',
);
ok(
  '明确禁止「汉字 + 西里尔/拉丁」拼接的怪词',
  P.includes('严禁把一个词写成'),
  '这是用户截图里 `霍贾and` / `斯皮塔梅en` / `哈萨克mys` 那一类',
);
ok(
  '要求译文里不得出现西里尔字母',
  P.includes('不得出现西里尔字母'),
);
ok(
  '没有相反的指令（不许出现「人名音译/译成中文」这类要求）',
  !/人名[^。\n]{0,20}(音译成中文|译成中文|翻成中文)/.test(P) &&
    !/音译人名/.test(P),
);

// ============================================================
// 三、结构性不变量：占位符与语言标签
// ============================================================

section('三、结构性不变量');

for (const ph of ['{LANG}', '{TITLE}', '{CONTENT}', '{CATEGORIES}']) {
  ok(`占位符 ${ph} 仍在（缺了就原样发给模型）`, P.includes(ph));
}

// 每种**源清单里声明过的语言**都要有像样的语言名。
// 漏一种 → 模型收到「其他语言」，等于没告诉它原文是什么语言。
{
  const langs = [...new Set(RSS_SOURCES.map((s) => s.language))].sort();
  for (const lang of langs) {
    const label = langLabel(lang);
    ok(
      `langLabel('${lang}') 有具体语言名（不是「其他语言」）`,
      label !== '其他语言',
      `得到「${label}」；源清单里新增了语言就要在 langLabel 里补上`,
    );
  }
}

// 民生必须真的是一个可选分类 —— 提示词让它「一律 true」，
// 但如果没有对应的 category id，模型只能硬塞进别的类里。
ok(
  '分类枚举里有 livelihood（民生）',
  (CATEGORY_IDS as string[]).includes('livelihood'),
  CATEGORY_IDS.join(', '),
);

// 提示词里不该泄漏「你是提示词/规则」这类元信息（模型会照抄进正文）
ok(
  '没有把「忽略以上指令」之类的注入痕迹留在正文要求里',
  !/忽略(以上|上面)指令/.test(P),
);

// ============================================================
// 汇总
// ============================================================

console.log(`\n${'='.repeat(64)}`);
if (failures.length === 0) {
  console.log(`✅ 全部通过：${passed} 项断言`);
  process.exit(0);
} else {
  console.log(`❌ ${failures.length} 项失败 / 共 ${passed + failures.length} 项：`);
  for (const f of failures) console.log(`   - ${f}`);
  process.exit(1);
}
