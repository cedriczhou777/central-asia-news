/**
 * 翻译提示词里的**产品口径**回归（离线，不联网、不调模型）。
 *
 * 用法：`pnpm test:translate-prompt`
 *
 * ## 为什么必须有这个脚本
 *
 * `translate.ts` 的 `TRANSLATE_PROMPT` 里装着两条**产品口径**：
 *
 * 1. **「投资者相关」的题材范围** = 政经 / 外资 / 工商税法 / 行业项目 / 社会民生。
 * 2. **人名保留拉丁字母**，不音译成汉字。
 *
 * 这两条**不在类型系统里**，也没有任何编译期检查 —— 提示词是一整块字符串，
 * 「顺手精简一下」就能把它们删掉，而症状要几天后才以
 * 「怎么没有民生新闻了」「人名怎么又译错了」的形式出现。
 *
 * 已经踩过一次：旧口径的正向清单是
 * 「经济形势、行业发展、能源/矿产/基建/制造业项目、外贸与投资协议、金融与汇率、
 * 国家政策法规、政局变动、影响营商环境的社会治安事件」，
 * **社会民生整类不在里面**，而负向清单里的「日常生活琐事」又很容易把它一起扫掉 ——
 * 于是物价、工资、补贴、税费这类**没有金额但直接决定消费能力与劳动力成本**的稿子
 * 在入库阶段就没了。所以下面有两条断言专门盯这件事：
 * 「五类正向题词都在」+「旧的『宁可从严』不许回来」。
 *
 * ## 为什么断言的是「句子在不在」而不是「模型判得对不对」
 *
 * 模型判得对不对要靠 `scripts/test-translate.ts`（真调模型，联网、要 Key）。
 * 本脚本管的是**更前面一层**：口径有没有被写进提示词。两层都要，
 * 因为「口径没写进去」和「写进去了但模型不听」是两种不同的故障，
 * 混在一起查会查错方向。
 */
import { TRANSLATE_PROMPT, langLabel, CATEGORY_IDS } from '../src/lib/translate';
import { RSS_SOURCES } from '../src/lib/data/rss-sources';

// ----- 极简断言（与其它 scripts/test-*.ts 同款，便于一起读输出）-----

let passed = 0;
const failures: string[] = [];

function ok(name: string, cond: boolean, detail = '') {
  if (cond) {
    passed++;
    console.log(`  ✓ ${name}`);
  } else {
    failures.push(`${name}${detail ? ` —— ${detail}` : ''}`);
    console.log(`  ✗ ${name}${detail ? ` —— ${detail}` : ''}`);
  }
}

function section(title: string) {
  console.log(`\n${'─'.repeat(64)}\n${title}\n`);
}

const P = TRANSLATE_PROMPT;

// ============================================================
// 一、相关性口径：正向清单必须完整包含五类
// ============================================================

section('一、相关性口径（正向清单五类）');

// 这五个词就是产品口径本身。少一个就说明有人改了范围。
for (const label of ['政经', '外资', '工商税法', '行业项目', '社会民生']) {
  ok(`正向清单含「${label}」`, P.includes(label));
}

// 光有「社会民生」这个标题不够 —— 要真的把具体题材列出来，
// 否则模型看到这四个字仍然不知道该不该放行物价稿。
for (const topic of ['物价', '工资', '就业', '补贴', '税费', '住房']) {
  ok(`社会民生列了具体题材「${topic}」`, P.includes(topic));
}

// ★ 回归点：正是这两句让民生稿子被扫掉。它们不许回来。
ok(
  '旧的「宁可从严」总则已移除（它会把正向清单里的题材一起压掉）',
  !P.includes('宁可从严'),
  '提示词里又出现「宁可从严」——除非确认要收紧，否则这是回归',
);
ok(
  '保留了「不要因为看起来不像投资新闻就判 false」的告诫',
  P.includes('不要因为') && P.includes('判 false'),
  '没有这条，模型会按「像不像投资新闻」的直觉把民生/税制类稿子判掉',
);

// 负向清单要还在（只加正向、不写负向 = 文体娱乐会涌进来）
ok('负向清单仍在（文体娱乐 / 生活方式 / 风俗礼节 / 社会琐事）',
  P.includes('文体娱乐') && P.includes('生活方式') && P.includes('风俗礼节'));

// ============================================================
// 二、人名写法：保留拉丁字母
// ============================================================

section('二、人名写法（保留拉丁字母）');

ok('提示词要求人名保留拉丁字母', P.includes('人名') && P.includes('拉丁字母'));
ok('明说不要音译成汉字', P.includes('不要') && P.includes('音译成汉字'));
ok(
  '给了具体转写示例（否则模型不知道「通行英文转写」长什么样）',
  P.includes('Tokayev'),
);
ok(
  '明确限定「只针对人名」，机构名/地名照常中文',
  P.includes('只针对人名') && P.includes('机构名'),
  '不限定的话模型会把所有专名都留成拉丁字母',
);
ok(
  '没有相反的指令（不许出现「人名音译/译成中文」这类要求）',
  !/人名[^。\n]{0,20}(音译成中文|译成中文|翻成中文)/.test(P) &&
    !/音译人名/.test(P),
);

// ============================================================
// 三、结构性不变量：占位符与语言标签
// ============================================================

section('三、结构性不变量');

for (const ph of ['{LANG}', '{TITLE}', '{CONTENT}', '{CATEGORIES}']) {
  ok(`占位符 ${ph} 仍在（缺了就原样发给模型）`, P.includes(ph));
}

// 每种**源清单里声明过的语言**都要有像样的语言名。
// 漏一种 → 模型收到「其他语言」，等于没告诉它原文是什么语言。
{
  const langs = [...new Set(RSS_SOURCES.map((s) => s.language))].sort();
  for (const lang of langs) {
    const label = langLabel(lang);
    ok(
      `langLabel('${lang}') 有具体语言名（不是「其他语言」）`,
      label !== '其他语言',
      `得到「${label}」；源清单里新增了语言就要在 langLabel 里补上`,
    );
  }
}

// 民生必须真的是一个可选分类 —— 提示词让它「一律 true」，
// 但如果没有对应的 category id，模型只能硬塞进别的类里。
ok(
  '分类枚举里有 livelihood（民生）',
  (CATEGORY_IDS as string[]).includes('livelihood'),
  CATEGORY_IDS.join(', '),
);

// 提示词里不该泄漏「你是提示词/规则」这类元信息（模型会照抄进正文）
ok(
  '没有把「忽略以上指令」之类的注入痕迹留在正文要求里',
  !/忽略(以上|上面)指令/.test(P),
);

// ============================================================
// 汇总
// ============================================================

console.log(`\n${'='.repeat(64)}`);
if (failures.length === 0) {
  console.log(`✅ 全部通过：${passed} 项断言`);
  process.exit(0);
} else {
  console.log(`❌ ${failures.length} 项失败 / 共 ${passed + failures.length} 项：`);
  for (const f of failures) console.log(`   - ${f}`);
  process.exit(1);
}
