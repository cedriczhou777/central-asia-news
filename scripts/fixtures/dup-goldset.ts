/**
 * **重复判定的金标准集**（2026-10-27 建）
 *
 * ## 为什么要有它（**这是今晚最重要的一件基础设施**）
 *
 * 2026-10-27 同一晚内，我在两处栽了**同一个错**：
 * ① `pair-split`：拿「同一批数据、两个 mode」对比，得出「簇内细分压倒性胜利」
 *    ⇒ ⇒ 后来把**同一个 mode 连跑两次**，结果不同（判是 6 组 2 / 判是 0 组 0）
 *    ⇒ ⇒ **那组对比两边都不可信** ⇒ ⇒ 结论作废、代码撤回。
 * ② `similarityFixed`：拿「判别力 = 真最低 − 假最高 **必须 > 0**」当判据
 *    ⇒ ⇒ 那个指标**过严**（地板本来就是切分线）⇒ ⇒ 差点误判成「没改进」。
 *
 * ⇒ ⇒ 两次的共同病根：**没有一把可靠的尺子**。
 * ⇒ ⇒ 这份金标准就是那把尺子：**人工逐条判读**的「这两条是不是同一件事」，
 * ⇒ ⇒ 有了它，任何「改进」都能被**可复现地**评估。
 *
 * ## 它怎么来的
 *
 * · 语料：线上真实入库标题（2026-10-27 / 2026-10-28 两批，五国）
 * · 候选：同国标题两两配对，`similarity ≥ 0.28`
 * · 抽样：**分层** —— 高区（sim ≥ 0.5）20 条 + 边界区（0.28 ≤ sim < 0.5）40 条
 *   （高区几乎全是真重复、没有区分力 ⇒ 区分力全在边界区）
 * · 标注：**逐条人工判读**（看完整两条标题，判断「是不是同一件事」）
 *
 * ## 标注里的两个约定（**判读时反复用到，写下来免得以后各判各的**）
 *
 * 1. **「同一事件的不同侧面」算真重复**。
 *    例：「国情咨文：宣布提高最低工资」vs「发表 2026 年国情咨文」= **真**。
 * 2. **「同一篇讲话里的两个不同要点」算假连接**。
 *    例：「指示批准新《民法典》」vs「指示金融部门加强反通胀」= **假**
 *    （它们共享「哈萨克斯坦总统托卡耶夫指示」这个长前缀 ⇒ **正是前缀过敏的典型样本**）。
 *
 * ⚠️ 数字互相矛盾的两条**算假**（不同来源/不同时点的报道，不能合并成一条稿）。
 */
