/**
 * 草稿封面（`thumb_media_id`）该取哪张图 —— 2026-09-29 新增。
 *
 * ## 为什么要有这个文件（用户的原话）
 *
 * > 我说过了越是相关的重要的新闻要放前面，ok，实在没有图也没有关系，但是你要知道
 * > **你的封面是以第一个新闻的照片做插图的**，所以，没有图的时候，你要不然把第二新闻
 * > 放在第一个位置，或者**直接使用第二个新闻的图片做封面**。
 *
 * 这条投诉对应的实现事实是：`route.ts` 里封面取的是
 * `wechatArticles[0]?.cover_image || … || undefined`，**只看第一条**，
 * 第一条没图就一路退到内置品牌图（一张没有任何信息的品牌占位图）。
 * 09-29 晚报的阿塞拜疆篇就是这样：第一条是「土耳其 TPAO 计划将每日石油产量提升至 100 万桶」
 * （AZERTAC 俄语源、无图），于是封面变成了纯品牌图 —— 用户贴出来的那张截图。
 *
 * ## 用户给的两个办法，各归一层，都要做
 *
 * 1. **「把第二新闻放在第一个位置」** ⇒ 属于**排序**，交给总审的提示词
 *    （`EDITOR_PROMPT` 第三件事里的「封面规则」）：让模型在有选择时，
 *    把有图且重要性相当的那条排到第一位。这一层只有模型能判「重要性相当」。
 * 2. **「直接用第二个新闻的图片做封面」** ⇒ 属于**渲染**，就是这个函数。
 *    它是一条纯兜底规则：**第一条没图就往后找，找第一条有图的**。
 *    这一层不需要判断重要性，所以也不需要模型 —— 而且它**必须**是确定性的：
 *    「今天封面是不是品牌图」不该取决于模型当天心情。
 *
 * 两层是**互补**的，不是二选一：提示词让封面尽量落在「重要的那条」上，
 * 这个函数保证「实在没有，也不会退成一张空图」。
 *
 * ## 一条边界：只取**本份日报内部**的图
 *
 * 候选只来自这份草稿自己的稿件。绝不搜图库、绝不生成图
 * （`article-format.ts` 现在正是把 unsplash/picsum 当**编造图**在拦）。
 * 用第 3 条的图当整份日报的封面是合理的 —— 这是一份**日报**，封面本来就是选一张代表图；
 * 而「去网上找一张看起来像的图」是**事实错误**，两者性质不同。
 */

/** 一个封面候选：一条稿件 + 它可用的封面图（没有就是空）。 */
export interface DraftCoverCandidate {
  title: string;
  imageUrl?: string;
}

/** 选中的封面：`index` 是它在**最终顺序**里的下标（0 表示就是第一条的图）。 */
export interface DraftCover {
  index: number;
  url: string;
  title: string;
}

/**
 * 从**最终顺序**的稿件里挑一张草稿封面：**第一条有图的**。
 *
 * - 第一条有图 ⇒ 返回 `index: 0`，行为与改动前完全一致（绝大多数轮次走这条）。
 * - 第一条没图、第 N 条有图 ⇒ 返回 `index: N`。`route.ts` 据此打日志、写进审计，
 *   所以「今天这份草稿的封面为什么不是第一条的图」永远有答案。
 * - 一条都没图 ⇒ 返回 `null`，由调用方退回内置品牌图（旧行为）。
 *
 * 返回 `index` 而不只是 URL，是因为**这条信息只有调用方用得着**：
 * 封面来自第 5 条 vs 第 1 条，是用户能一眼看到差别、而排查时必须能区分的一件事
 * （「封面是品牌图」和「封面是第 5 条的图」在后台看起来都只是「有封面」）。
 */
export function pickDraftCover(articles: DraftCoverCandidate[]): DraftCover | null {
  for (let i = 0; i < articles.length; i++) {
    const a = articles[i];
    const url = (a?.imageUrl || '').trim();
    if (url) return { index: i, url, title: a?.title || '' };
  }
  return null;
}
