/**
 * 一条「元首写法不对」的记录。
 *
 * `kind` 的两种取值对应**两种修法完全不同**的缺陷，混在一起就没法写修正指令：
 *   · `latin` —— 该写中文却写了拉丁（**同一个人**，只是写法不对）⇒ 直接换写法；
 *   · `not-head-of-state` —— 「总统」后面那个人**根本不是元首** ⇒
 *     不能靠替换名字修，要按原文职务改写（2026-10-11 的 `id=11360` 就是这一类：
 *     原文是 `Исфандиёр Саъдулло`，一个官员，模型给他加了「总统」头衔）。
 */
export interface HeadOfStateHit {
  kind: 'latin' | 'not-head-of-state';
  /** 命中的原文片段（给人看的上下文） */
  sample: string;
  /** 该国的元首约定俗成中文名 */
  right: string;
  /** 该国的中文名（写进修正指令） */
  country: string;
  /** 为什么错 —— 会进日志与重试修正指令，必须写成人话 */
  why: string;
}

/**
 * 扫出「元首写法不对」的两类问题。
 *
 * ## 判据（顺序即规则）
 *
 * 1. **拉丁写法**：某国元首的 `latin` 写法出现在**紧邻职务词**（`总统`/`国家元首`，
 *    中间允许空格与 `·`）或**紧跟在该国国名之后**的位置 ⇒ 命中。
 *    ⚠️ 为什么必须带上下文：`Aliyev` / `Rahmon` 这类姓氏在别国稿子里也会指别人，
 *    全局匹配会把「某位姓阿利耶夫的部长」也拦下 —— 而重试三次不过就**丢稿**。
 * 2. **「总统」+ 名·姓，但那个人不是元首**：`〈目标国名〉总统〈名·姓〉` 命中且该姓名
 *    不在**任何**一国的元首写法里 ⇒ 命中。
 *    ⚠️ 要求名字里带中点（中亚人名在中文里几乎总写成「名·姓」）：
 *    不加这条的话「总统新闻局」「总统会见」「总统办公厅」这类都会被抓成「名字」。
 *    ⚠️ **两段的字宽是量出来的，不是拍的** —— 这一步走了三版，过程值得留着：
 *    ① 初版 `{2,4}·{2,10}`：用户 2026-10-11 报的那条真案例是
 *       「塔吉克斯坦总统**伊斯坎德尔**·萨德洛夫」，名 5 字 ⇒ **初版一条都抓不到**，
 *       闸门装了等于没装；
 *    ② 放宽到 `{2,8}·{2,12}`：在 2154 篇真实语料上命中 38 条，逐条判读
 *       **36 真 / 2 误** —— 两条误报是 `阿塞拜疆总统**特别代表**马西姆·马马多夫`、
 *       `乌兹别克斯坦**总统府发言人**谢尔兹德·阿萨多夫`（把职务当成了名字首段）；
 *    ③ 现版 `{2,5}·{2,8}`：实测的中文音译名首段全在 3–5 字
 *       （埃莫马利/沙夫卡特/萨德尔/萨迪尔/萨达尔/伊利哈姆/伊尔哈姆/伊斯坎德尔/
 *       谢尔盖/谢尔盖特/谢尔盖夫/谢尔兹德），限到 5 字后**两条误报同时消失、
 *       真缺陷一条不少**（详见 `BASELINE_2026-10-11.md` 的实测表）。
 *    ⚠️ 顺手记一条：`not-head-of-state` 的白名单比对**必须用前缀、不能用全等** ——
 *    中文没有词边界，正则只能贪心地把中点之后的词一起吞进来
 *    （`沙夫卡特·米尔济约耶夫提出推动中亚`），全等比对会把**每一篇正确的稿子**判死。
 *    详见函数体内那段 ⚠️⚠️ 注释。
 *    ⚠️ 中点只认 `·` `•` `‧`三个，**刻意不含连字符 `-`**：
 *    哈萨克斯坦元首的正式中文写法是「哈斯穆**-卓玛尔特**·托卡耶夫」，
 *    把 `-` 也当分隔符会让正则从「哈斯穆-卓玛尔特」处起匹配、
 *    切出一个**不在白名单里**的假名字 ⇒ 每一篇正确的哈萨克斯坦稿子都被拦。
 *    ⚠️ 只认 5 个**目标国**作前缀：「阿塞拜疆总统阿利耶夫会见**俄罗斯**总统普京」
 *    里的普京是**别国**元首，不在本表里，靠「俄罗斯不在目标国名单里」自然放行。
 *    ⚠️ `\\s{0,3}` 只允许**空白**，所以在中文正文里等价于「必须紧邻」——
 *    「哈萨克斯坦总统任命阿依古丽·X 为…」这种句式不会命中（中间隔着「任命」）。
 *
 * ## 已知盲区（**有意保留**）
 *
 * 元首名字只出现姓氏、且没有「总统」/国名做上下文时（例如「扎帕罗夫指出…」写成
 * 「Zhaparov 指出…」），第 1 条抓不到。补它要放弃上下文约束，
 * 换来的是「部长 Aliyev 被强行改成总统阿利耶夫」——那是**制造**事实错误，
 * 比漏一处写法严重得多。按项目纪律「下游是重试/丢稿的判据宁漏不误杀」，这是有意的取舍。
 *
 * ## ⚠️ 判据**不看「这篇稿子属于哪个国家」**
 *
 * 五国元首的中文写法是**同一套**标准：「吉尔吉斯斯坦的稿子里把总统写成
 * `Sadyr Zhaparov`」与「哈萨克斯坦的稿子里把吉尔吉斯斯坦总统写成拉丁」，
 * 是同一种错，都要修。所以 `countryCode` **只用来把本国那一条排在前面**
 * （日志与修正指令都只取前几条），**不用来过滤** ——
 * 也因此它允许是 `null`（稿子被归错国时，写法照样要修）。
 */
export function checkHeadOfStateNames(countryCode: CountryCode | null, text: string): HeadOfStateHit[] {
  const hits: HeadOfStateHit[] = [];
  /** 本国的中文名 —— **只用于排序**。 */
  const ownName = countryCode ? countryList.find((c) => c.code === countryCode)?.name : undefined;
  /** 代码 → 中文国名（查不到时回落成代码，不抛）。 */
  const nameOf = (code: CountryCode) => countryList.find((c) => c.code === code)?.name ?? code;

  // ---- 1) 拉丁写法（带上下文） ----
  // 上下文 A：「〈职务词〉 〈拉丁名〉」
  // 上下文 B：「〈目标国名〉 〈拉丁名〉」（职务词可能被省掉或写在后面）
  const officeWords = ['总统', '国家元首'];
  const countryRe = TARGET_COUNTRY_NAMES.map((c) => escapeRe(c.name)).join('|');
  for (const code of Object.keys(HEAD_OF_STATE) as CountryCode[]) {
    const spec = HEAD_OF_STATE[code];
    const latinRe = spec.latin.map(escapeRe).join('|');
    const ctxA = new RegExp(`(?:${officeWords.join('|')})\\s*[·•]?\\s*(${latinRe})\\b`);
    const ctxB = new RegExp(`(?:${countryRe})\\s{0,3}(${latinRe})\\b`);
    for (const re of [ctxA, ctxB]) {
      const m = re.exec(text);
      if (m) {
        hits.push({
          kind: 'latin',
          sample: m[0].trim(),
          right: HEAD_OF_STATE[code].zhFull,
          country: nameOf(code),
          why:
            `${HEAD_OF_STATE[code].zh} 的写法必须是中文「${HEAD_OF_STATE[code].zhFull}」` +
            `（约定俗成的中文译名），不能写拉丁转写「${m[1]}」`,
        });
        break; // 同一个国家只报一条，避免同一篇里重复记账
      }
    }
  }

  // ---- 2)「总统」后面跟了一个「名·姓」，但那人不是任何一国的元首 ----
  //
  // ⚠️⚠️ **白名单必须用「前缀」比对，不能用「全等」** —— 这是实测出来的，
  // 差一点就把闸门做成了误报机器：
  // 中文没有词边界，正则只能贪心地把「中点之后的一串汉字」一起吞进来，于是
  //   正文 `乌兹别克斯坦总统沙夫卡特·米尔济约耶夫提出推动中亚与阿塞拜疆合作…`
  // 捕获到的是 `沙夫卡特·米尔济约耶夫提出推动中亚`（名字 + 动词 + 宾语），
  // 用 `===` 比对白名单必然不等 ⇒ **每一篇正确的乌兹别克斯坦稿子都被判不合格**。
  // 2026-10-11 在 2154 篇真实语料上量到：全等版 `not-head-of-state` 命中里
  // **绝大多数是这种「正确名字 + 后续词语」**。改成 `startsWith` 后误报归零（见脚本实测）。
  // 前缀比对不会漏掉真缺陷：错写法（`贾帕罗夫`/`米尔济约夫`/`伊斯坎德尔·萨德洛夫`）
  // **都不是**任何一个正确写法的前缀。
  // ⚠️ **名字首段限 `{2,5}`，这条是量出来的第二个坑**（2026-10-11，2154 篇语料）：
  // 写成 `{2,8}` 时，`阿塞拜疆总统**特别代表**马西姆·马马多夫` 与
  // `乌兹别克斯坦**总统府发言人**谢尔兹德·阿萨多夫` 这两条**正确地**提到官员的稿子
  // 会被切出一个「特别代表马西姆·马马多夫」「府发言人谢尔兹德·阿萨多夫」的假名字
  // ⇒ 判不合格。限到 5 字之后两条误报同时消失，而实测要抓的真缺陷一个不少：
  // 埃莫马利(4)/沙夫卡特(4)/萨德尔(3)/萨迪尔(3)/萨达尔(3)/伊利哈姆(4)/伊尔哈姆(4)/
  // 伊斯坎德尔(5)/谢尔盖(3)/谢尔盖特(4)/谢尔盖夫(4)/谢尔兹德(4) —— 全在 3–5 之间。
  // 已知漏面：首段 >5 字的中文音译名（如「哈斯穆卓玛尔特」7 字）不判 ——
  // 而那正是本表里**已经正确**的写法，漏它没有代价。
  for (const c of TARGET_COUNTRY_NAMES) {
    const re = new RegExp(
      `${escapeRe(c.name)}\\s{0,3}(?:${officeWords.join('|')})\\s{0,3}([\\u4e00-\\u9fa5]{2,5}[·•‧][\\u4e00-\\u9fa5]{2,8})`,
    );
    const m = re.exec(text);
    if (!m) continue;
    const name = m[1];
    // 是某国元首的写法（允许后面还粘着后续词语）⇒ 放行
    if (allZhForms().some((f) => name.startsWith(f))) continue;
    const zhFull = HEAD_OF_STATE[c.code].zhFull;
    hits.push({
      kind: 'not-head-of-state',
      sample: m[0].trim(),
      right: zhFull,
      country: nameOf(c.code),
      why:
        `「${c.name}${HEAD_OF_STATE[c.code].office}」后面跟的不是` +
        `${nameOf(c.code)}元首的约定俗成写法 ——` +
        `${nameOf(c.code)}${HEAD_OF_STATE[c.code].office}是「${zhFull}」` +
        `（姓氏可只写「${HEAD_OF_STATE[c.code].zh}」）。` +
        `若原文里此人并不担任该职务，必须按原文写的职务改写，**不要给他加上元首头衔**`,
    });
  }

  // 本国的那一条排在前面（日志与修正指令都只取前几条，本国的信息量最大）。
  if (ownName) {
    hits.sort((a, b) => (a.country === ownName ? 0 : 1) - (b.country === ownName ? 0 : 1));
  }
  return hits;
}

/**
 * 渲染「本条所属国家的元首是谁」，注入翻译提示词的 `{HEADSOFSTATE}` 占位符。
 *
 * **必须是生成式的**（与 `currencyPromptTable` 同一个理由）：手写在提示词里的名字
 * 迟早会与 `HEAD_OF_STATE` 分叉，而分叉的后果是「模型按 A 写、闸门按 B 判」，
 * 每篇都过不了闸 ⇒ 三次重试用完 ⇒ 丢稿。
 *
 * ⚠️ 第二句那句禁令**不能省**：只给名字会让模型把它当成「素材」补进正文主语
 * （2026-10-01 实测过，见文件头）。给的是**写法**，不是**素材**。
 *
 * 传入的 `countryName` 是**中文国名**（`translateNews` 收到的那一个），
 * 与 `countryCodeByName` 是同一个输入，避免「提示词说 A 国、闸门按 B 国判」。
 */
export function headOfStatePromptLine(countryName: string): string {
  const code = countryCodeByName(countryName);
  if (!code) return '';
  const s = HEAD_OF_STATE[code];
  return (
    `${countryName}的${s.office}是**${s.zhFull}**（正文里可只写姓氏「${s.zh}」）。` +
    `原文提到这位元首时，一律用这个中文写法，**不要写拉丁转写**、也不要换用别的汉字。` +
    `⚠️ **原文没有提到元首时，译文里就不许出现元首的姓名或职务** ——` +
    `这一条只告诉你「该用哪个写法」，不是让你把元首补进正文。`
  );
}

