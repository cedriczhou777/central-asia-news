/** 一条「日期缺月份」的记录。 */
export interface DateAmbiguity {
  /** 命中的日期片段（去空格后） */
  samples: string[];
  why: string;
}

/**
 * 「日/号」出现但**通篇没有任何月份** ⇒ 日期有歧义。
 *
 * ## 实测来源（2026-10-11，用户报的第 4 条）
 *
 * `id=12510`：原文 `Иш-чаралар 23-25-октябрь күндөрү Бишкек шаарындагы…`
 * （活动在**10月23–25日**），译文是：
 * 「吉尔吉斯斯坦**23日至25日**在比什凯克举办"AgroTechExpo-2026"展会…」
 * —— **月份在原文里有，是翻译丢的**，用户得自己查才知道是 10 月。
 *
 * 同类：`id=12434` 原文 `11-14 октября … посетят`（10月11–14日访问），
 * 摘要写成「将于 **11-14 日**对哈萨克斯坦进行国事访问」。
 *
 * ## 判据（两步，都是**存在性**判断，不靠阈值）
 *
 * 1. 通篇出现了月份标记（`10月` / `十月` / `本月`）⇒ 直接放行（绝大多数稿子）；
 * 2. 通篇没有月份，但出现了「1–31 的日/号」⇒ **命中**。
 *
 * ⇒ 「日期不许裸写」这件事在中文新闻里是硬要求：只写「23–25日」读者无法确定是哪个月。
 *   这与货币闸同属「两个事实的合取」，不是概率判断。
 *
 * ## 假阳性防线（**每一条都对应一个会在真实语料里出现的写法**）
 *
 * · `第 5 号总统令` —— 前面的「第」是硬排除（提示词里 `№5` 就要求译成这个形式）；
 * · `1 号公路 / 2 号线 / 3 号机组 / 4 号文件` —— 后面跟的是**非日期名词**时跳过。
 *   ⚠️ 匹配前先**去掉所有空白**：库里写的是「第 5 号」（带空格），
 *   带空格的 lookbehind 在 JS 里写不出来，去空格是最省事又不会漏的做法。
 *
 * ## 已知盲区（**有意保留**）
 *
 * 判据扫的是 `title + summary + content` 的合并文本（与货币闸同口径）。
 * 于是「摘要里裸写、正文里写了月份」抓不到 —— 上面 `id=12434` 就是这种形态
 * （摘要裸写，正文里有「11 月」）。不改成逐字段各判一次的理由同货币闸：
 * 逐字段会误杀合法写法，而这里下游是重试 ⇒ 宁漏不误杀。
 */
/**
 * 「这篇稿子里提到过月份」的判据。
 *
 * ⚠️ 这一侧**必须往宽了写**（宽 ⇒ 判成「有月份」⇒ 放行）。两侧代价不对称：
 * 漏一次 = 这一篇日期仍然缺月份（用户看得见，下次还会报）；
 * 严一次 = **误拦好稿 → 重试 → 可能丢稿**（看不见，本项目最忌讳的形态）。
 * 所以：
 *   · 阿拉伯数字与全角数字都收（模型偶尔输出全角）；
 *   · 汉字数字收（`十月`）；
 *   · **「本月/下月/上月/当月/同月/每月/次月/该月/首月」这类相对月份也收** ——
 *     它们同样让读者知道是哪个月，却一个数字都没有。只认「数字+月」的话，
 *     `会议于本月 5 日举行` 会被判成「日期缺月份」，**那是误报**。
 *     （刻意不收「明月/来月」这类在中文里不是月份的词 —— 收了只会让它更宽，
 *     虽然方向安全，但没必要把噪声写进判据。）
 */
const MONTH_RE =
  /(?:[0-9０-９]{1,2}|[一二三四五六七八九十百]{1,3}|本|下|上|当|同|每|次|该|首)月/;

/**
 * 「日/号」后面跟这些词时它不是日期（**每一条都是实测出来的，不是预防性加码**）。
 *
 * 2026-10-11 在 2154 篇真实语料上第一次量：命中 16 条，逐条判读 **8 真 / 8 假**——
 * 误报率 50%，绝不能这样进闸。8 条假阳性分成两类，下面这两组词就是照它们补的：
 *
 * · **门牌 / 地址**（6 条）：`伊斯拉姆·卡里莫夫街 8 号`、`米恩-库什街 21 号`、
 *   `内沙米区 28 号街`、`哈利勒巴耶夫街 7 号`、`大道 3 号`、`36/1 号建筑工地`。
 *   两条路：① 匹配前看**前一个字符**（街/路/巷/弄/道/栋/幢/座/室/楼，写在下面的
 *   lookbehind 里）⇒ 前一类；② 匹配后看**后一个字符**（`号街` 这种「街区名」写法）
 *   ⇒ 下面这个表里的 `街|路|巷|弄`。
 * · **时长量词**（1 条）：`被判处 10 日行政拘留` —— 「N 日」在这里是**刑期**不是日期
 *   （⇒ 下面表里的 `行政|拘留|监禁`）。
 * · 另有 1 条既不是日期也不是门牌：`第 245 号许可证`（已被 `第` 挡掉）。
 *
 * ⚠️ 刻意**没有**把「区」加进那个 lookbehind：`塔什干州奇纳兹区 9 日举行…` 是**真日期**，
 * 加了会把真缺陷一起挡掉。也刻意**没有**加「的」：`23 日的活动` 恰恰就是**缺月份**的
 * 那种真缺陷，加了等于把判据关掉。
 */
const NON_DATE_AFTER = /^(?:公路|国道|号线|线|频道|台|中学|小学|学校|医院|幼儿园|令|文件|议案|决议|公告|指示|命令|机组|锅炉|库|桥|坝|区|栋|楼|车厢|站台|街|路|巷|弄|行政|拘留|监禁)/;

/**
 * **原文里**出现「月份」的线索（多语言）。
 *
 * 只服务于一件事：原文本身就没有月份时，`checkDateMonthAmbiguity` **不管**。
 * 为什么必须有这个出口：译文只写「23 日」而原文写的是 `23-25 октября`，那是
 * **翻译把信息丢了**（该修）；但原文本身就只写「9-го числа」时，逼模型补一个月份
 * 等于**让它编**，它编不出来就会被重试三次然后**丢稿** ——
 * 而项目纪律是「宁可留重复（看得见），不要丢稿（看不见）」。
 * 2026-10-11 把 8 条实测命中逐条拉原文核对：**8/8 的原文里都有月份**
 * （`9 қазан`、`6 октября`、`8-9-октябрда`、`5 октября`、`8-9 октября`…），
 * 所以这个出口在实测样本上**没有吞掉任何一条真缺陷**。
 *
 * ⚠️ 词干故意写短（`октябр` 而不是 `октябрь`）：原文有变格，
 * `октября` / `октябрда` / `oktyabrda` 都得命中。代价是要防「词干是别的词的子串」，
 * 下面每一条后缀边界都是**照真实副作用**加的、不是预防性加码：
 *   · `ма[йя]` 带后缀边界 —— 否则吉尔吉斯语 `майдан`（广场，**地址里很常见**）会命中；
 *   · 阿塞拜疆语 `may` 同理（`Mayami`）；
 *   · 三字母英文缩写必须带左右边界 —— 否则 `nov` 会命中 `novosti`（新闻，**几乎每篇都有**）。
 */
const SOURCE_MONTH_RE = new RegExp(
  [
    '月',
    'январ|феврал|март|апрел|июн|июл|август|сентябр|октябр|ноябр|декабр', // ru / ky
    'ма[йя](?![а-яё])',
    'қаңтар|ақпан|наурыз|сәуір|мамыр|маусым|шілде|тамыз|қыркүйек|қазан|қараша|желтоқсан', // kk
    'yanvar|fevral|mart|aprel|iyun|iyul|avqust|sentyabr|oktyabr|noyabr|dekabr', // az
    'may(?![a-z])',
    '(?:^|[^a-z])(?:jan|feb|mar|apr|jun|jul|aug|sep|oct|nov|dec)(?![a-z])', // en
  ].join('|'),
  'i',
);

/**
 * @param text 译文（`title + summary + content` 合并）
 * @param originalText 原文（`originalTitle + originalContent`）。
 *   **传 `undefined` = 调用方拿不到原文**（探针、离线单测），此时照常判；
 *   传了字符串而里面没有月份线索 ⇒ 直接放行（见 `SOURCE_MONTH_RE` 的说明）。
 */
export function checkDateMonthAmbiguity(text: string, originalText?: string): DateAmbiguity | null {
  if (originalText !== undefined && !SOURCE_MONTH_RE.test(originalText)) return null;
  // 去空白：库里写「第 5 号」「23 - 25 日」，带空格的 lookbehind 在 JS 里表达不了。
  const t = text.replace(/\s+/g, '');
  if (MONTH_RE.test(t)) return null;

  const samples: string[] = [];
  // ⚠️ 三个 lookbehind 各挡一类：`第`（编号）、数字与 `/`（`36/1号` 这类楼号）、
  // 地址通名（`街 8 号`）。
  const re = /(?<!第)(?<![0-9/／])(?<![街路巷弄道栋幢座室楼])([0-9]{1,2})([日号])/g;
  for (const m of t.matchAll(re)) {
    const n = Number(m[1]);
    if (!(n >= 1 && n <= 31)) continue;
    const end = (m.index ?? 0) + m[0].length;
    if (NON_DATE_AFTER.test(t.slice(end, end + 3))) continue;
    samples.push(m[0]);
  }
  if (samples.length === 0) return null;
  return {
    samples: [...new Set(samples)].slice(0, 6),
    why:
      `日期只写了「${[...new Set(samples)].slice(0, 3).join('、')}」而**通篇没有月份** —— ` +
      `读者无法判断是哪个月（原文里的月份必须译出来，例如「23-25 октября」→「10月23日至25日」）`,
  };
}

