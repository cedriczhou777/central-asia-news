/**
 * 一个国家的国家元首。
 *
 * ## 为什么这张表必须存在（而不是「让模型自己判断」）
 *
 * 提示词第 6 条从 2026-09-28 起就写着「本条所属国家的国家元首写中文」，
 * 但**没有给名字**（当时是故意的：怕示例被搬去当主语，见文件头 ⚠️）。
 * 2026-10-11 实测的后果是三种写法并存：
 *
 * | 写法 | 条数 | 典型 |
 * |---|---|---|
 * | `Sadyr Zhaparov`（拉丁） | 4 | id 12504 / 12505 / 12506 / 12530 |
 * | 「萨德尔·贾帕罗夫」 | 4 | id 12502 / 12503 / 12521 / 12532 |
 * | 「萨德尔·朱帕罗夫」 | 1 | id 12509 |
 * | **「萨德尔·扎帕罗夫」（约定俗成）** | **0** | —— |
 *
 * ⇒ 「只说『写中文』不给名字」等于把**转写**这件确定性的事交给模型去猜。
 *   猜出来的是三个不同的答案。这与货币那条是同一个形状：
 *   不给「哪国用哪个」，它就会用唯一见过的那个。
 *
 * ## ⚠️ 注入提示词时要配一句禁令（否则会制造新错误）
 *
 * 只给名字会诱发 2026-10-01 已实测过的那个坑：模型把提示词里的领导人名
 * **搬去当正文主语**（一篇只有交通部的公路稿被写成「〈某国总统〉政府完成…」）。
 * 所以 `headOfStatePromptLine()` 里带了一句
 * 「**原文没有提到元首时，译文不许出现元首姓名**」——
 * 给的是**写法**，不是**素材**。
 */
export interface HeadOfStateSpec {
  /** 职务（中文）。目前五国全是「总统」，但字段留着 —— 换了政体只改这里。 */
  office: string;
  /**
   * ★ **约定俗成的中文写法**（**唯一口径**：提示词与闸门共用这一份）。
   *
   * 取的是**姓氏**（中文媒体与官方文件里的常用形式），因为正文里绝大多数场合
   * 只写姓氏（「总统扎帕罗夫」）；需要全名时用 `zhFull`。
   */
  zh: string;
  /** 全名（中文）。首次出现或正式的国事报道里用。 */
  zhFull: string;
  /** 该全名的其它可接受中文写法（不同媒体的通用变体）。 */
  zhAliases: string[];
  /**
   * 该元首在**原文**里的拉丁/俄语转写写法（大小写不敏感）。
   *
   * ⚠️ **只在「紧邻职务词」或「紧跟在国名之后」时才判命中**（见 `checkHeadOfStateNames`）——
   * 这些姓氏（尤其 Aliyev / Rahmon）在别国稿子里也会指**别的人**，
   * 无上下文地全局匹配会误杀，而误杀的代价是「重试三次 → 丢稿」。
   */
  latin: string[];
}

