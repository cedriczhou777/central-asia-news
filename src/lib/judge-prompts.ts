/**
 * 「同一件事」判组提示词的**版本注册表**。
 *
 * ## 为什么要有这个文件
 *
 * 提示词是一整块字符串，改了它在接口响应里**完全看不出来** —— 和 `scheduler.ts`
 * 里那个 cron 时刻是同一类问题。而判组这条链路改动**唯一的验收手段**是跑影子运行
 * 看逐对判定：如果分不清「这次跑的是哪一版判据」，旧版的结论就会被当新版读，A/B 等于白跑。
 *
 * 更麻烦的是**数据会漂移**：`days=1` 的窗口随日期滑动，两次运行喂给模型的候选对
 * 本来就不一样。那样比出来的差异，分不清是「提示词改了」还是「今天新闻换了」。
 *
 * ⇒ 解法是把版本做成**可切换的运行时参数**（与 `judge=think|nothink`、`mode=pair|group`
 * 同一套路子）：`GET /api/dedupe-check?...&pv=1`。同一个请求、同一批数据、同一条通道，
 * **唯一变量就是提示词版本**。
 *
 * ## v1 为什么要一直留着
 *
 * v1 是 2026-09-24 校准之前的判据 —— 也就是「如果当时把 L2 打开，模型会怎么判」的
 * **对照组**。留着它有两个必要用途：
 *
 *   1. **回归可控**：将来再改提示词，`pv=1` 随时能在同一批数据上给出基线，
 *      「这次改动到底动了哪几对」是可数的，不靠记忆。
 *   2. **失败可复现**：`mode=group` 保留 group 形态是为了原地重现那次乱合并，
 *      同理 `pv=1` 保留的是「漏合并（用户报的重复）」那一版判据。
 *
 * ⚠️ **v1 是冻结副本，永远不要改它。** 它不是「旧代码」，是**测量工具**。
 * 改了就失去了基线，之前所有的 A/B 数字全部作废。
 */

/**
 * 标题截断长度。放在这里而不是 `same-event.ts`，是为了让本模块不反向依赖它
 * （否则 `same-event` ← `judge-prompts` ← `same-event` 成环）。
 * `same-event` 从这里 import，保证两边只有一个真值。
 */
export const TITLE_MAX = 80;

/** 提示词只需要标题；用结构类型而不是 import `StoryLike`，避免循环依赖 */
export interface PromptItem {
  title?: string | null;
}

export type PromptPair = { a: number; b: number };

/** 每行一对：`编号 | 标题A || 标题B`。三个版本共用这段排版，保证差异只在「判据正文」。 */
function renderPairs(pairs: PromptPair[], items: PromptItem[]): string[] {
  return pairs.map((p, idx) => {
    const t1 = (items[p.a]?.title || '').slice(0, TITLE_MAX);
    const t2 = (items[p.b]?.title || '').slice(0, TITLE_MAX);
    return `${idx} | ${t1} || ${t2}`;
  });
}

/**
 * ## v1 —— 2026-09-21 pair 形态上线时的判据（**冻结，勿改**）
 *
 * 特征：**只有反例、没有正例细化**，末句是「拿不准就判『否』」。
 * 在 `JUDGE_TEMPERATURE = 0` + 兜底通道 `zhipu-flash` 下，漏合并是**系统性**的：
 * 2026-09-24 实测 az 一批 12 对候选里，用户报的那三条 Unibank（同一产品、三家媒体各写一篇）
 * 被判「否」，`阿塞拜疆与塞尔维亚战略伙伴关系` vs `…关系关系`（笔误）也判「否」。
 */
function buildV1(pairs: PromptPair[], items: PromptItem[]): string {
  return [
    '下面是若干对新闻标题（每对一行，行首是编号）。请**逐对**判断：这一对讲的是不是同一件事。',
    '',
    '算同一件事：同一次会议 / 同一次签约 / 同一份公告 / 同一条政策 / 同一个项目的重复报道。',
    '即使来源不同、措辞不同、详略不同、细节数字有出入，也算同一件事。',
    '',
    '判断方法：先在心里把两条各自概括成「谁 + 做了什么 + 在哪」，',
    '只有当两次概括指的是**同一次具体活动**时才判「是」。',
    '',
    '不算同一件事（务必判「否」）：',
    '  · 同一个组织 / 同一个城市办的**不同活动**：「上合组织反垄断机构负责人会议在杜尚别举行」',
    '    与「上合组织经贸部长会议在杜尚别举行」—— 主办方和地点都一样，但这是两场不同的会议',
    '  · 不同主体做同类事：「土耳其大使馆祝贺主权日」与「以色列大使馆祝贺主权日」',
    '  · 方向相反：「金价下跌」与「金价上涨」',
    '  · 不同地点/不同项目：「东哈萨克斯坦州建桥」与「阿斯塔纳建桥」',
    '  · 不同人物：「运动员甲夺金」与「运动员乙夺金」',
    '  · 只是同属一个话题、同一类机构、同一个州/部委 —— 话题相同不等于同一件事',
    '  · 两条讲的是同一主题但各自独立发生的不同事件',
    '',
    '拿不准就判「否」：把两条不同的新闻合成一条是**丢信息**，比留下重复更糟。',
    '',
    '只输出 JSON，不要解释。把**判为是同一件事**的编号列出来：',
    '{"same": [1, 4]}',
    '若一对都不是，输出 {"same": []}。',
    '',
    '# | 标题A || 标题B',
    ...renderPairs(pairs, items),
  ].join('\n');
}

/**
 * ## v3 —— 2026-09-24 第二次校准
 *
 * ### 相对 v2 改了什么、为什么
 *
 * v2 补了两类正例（换词重写 / 标题笔误）后，在同一批 12 对候选上实测：
 * **修好 2 对、回退 1 对**。回退的那对是
 * `阿塞拜疆与中国主要企业合作近 50 个联合项目` ↔ `…与中国大型企业合作推进约 50 个联合项目`
 * （sim 0.56，v1 判「是」、v2 判「否」）。诊断：`主要企业` / `大型企业` 撞上了反例里
 * 「**不同主体**做同类事」那一条 —— 反例没界定「不同主体」的判据，模型把**同义指代**
 * 也当成了两个主体。这是「加反例」和「加正例」互相打架的典型。
 *
 * 另有一个 v2 **没修好**的：`阿塞拜疆否认准备对柴油出口实施 90 天禁令的消息` ↔
 * `《Politico》：阿塞拜疆准备对柴油燃料出口实施 90 天禁令`（sim 0.44），v1 判「是」、
 * v2 仍然判「是」。v2 已经把这条写成了反例，**但只加例子不管用** —— 这类标题字面重叠
 * 最高（只差「否认」两个字），模型顺着相似度就判「是」了。
 *
 * ⇒ v3 的两处改动都不是「再加一个例子」，而是**改判据结构与判断顺序**：
 *
 *   1. 反例里给「不同主体」下**可操作的判据**（必须是不同的具体国名/公司名/人名），
 *      并补正例形态三（同义指代、数字表述差异 → 判「是」）。
 *   2. 把「相反的事实」检查**提到判断方法里作为第一步**，并点明「否认」是核心事实而非修饰语。
 *      放在反例清单里等着模型自己比对，实测不生效。
 *
 * ⚠️ 仍然保留末句「拿不准就判『否』」：误合并是**不可逆丢信息**，
 * 而漏合并至少还能靠人发现并补。这个方向不因为「用户报的是漏合并」就翻转。
 */
function buildV3(pairs: PromptPair[], items: PromptItem[]): string {
  return [
    '下面是若干对新闻标题（每对一行，行首是编号）。请**逐对**判断：这一对讲的是不是同一件事。',
    '',
    '算同一件事：同一次会议 / 同一次签约 / 同一份公告 / 同一条政策 / 同一个项目的重复报道。',
    '即使来源不同、措辞不同、详略不同、细节数字有出入，也算同一件事。',
    '  · 常见形态一：**同一家公司/机构发布了同一个产品、政策或计划，几家媒体各自写了一篇。**',
    '    「Unibank 推出绿色贷款，年利率从 12% 起」与「Unibank 推出面向企业主的绿色信贷：年利率低至 12%」',
    '    讲的是同一次发布 —— **不同媒体换词重写是同一件事最常见的形态**，判「是」。',
    '  · 常见形态二：**其中一条标题有笔误、重复字或被截断。**',
    '    「阿塞拜疆与塞尔维亚讨论战略伙伴关系」与「阿塞拜疆与塞尔维亚战略伙伴关系关系」，判「是」。',
    '  · 常见形态三：**两条只是措辞不同 —— 用近义词指同一个对象，或数字表述不一样。**',
    '    「阿塞拜疆与中国主要企业合作近 50 个联合项目」与「阿塞拜疆与中国大型企业合作推进约 50 个联合项目」',
    '    「主要企业 / 大型企业」是同一批人的两种说法，「近 50 个 / 约 50 个」是同一个数，判「是」。',
    '',
    '判断方法：先在心里把两条各自概括成「谁 + 做了什么 + 在哪」，',
    '只有当两次概括指的是**同一次具体活动**时才判「是」。',
    '',
    '**但先做一步「相反事实」检查**：一条是不是在**否认 / 辟谣 / 驳斥**另一条讲的那件事？',
    '是就直接判「否」，不用再比字面重叠度 —— 这类标题恰恰重叠度最高，顺着相似度会判错。',
    '',
    '不算同一件事（务必判「否」）：',
    '  · **一条在「否认 / 辟谣 / 驳斥」，另一条就是那条被否认的消息本身** —— 两条讲的是',
    '    **相反的事实**。注意「否认」不是修饰语，**它就是那条新闻的核心事实**，合并会丢掉它：',
    '    「阿塞拜疆否认准备对柴油出口实施 90 天禁令的消息」与',
    '    「《Politico》：阿塞拜疆准备对柴油燃料出口实施 90 天禁令」',
    '  · 同一个组织 / 同一个城市办的**不同活动**：「上合组织反垄断机构负责人会议在杜尚别举行」',
    '    与「上合组织经贸部长会议在杜尚别举行」—— 主办方和地点都一样，但这是两场不同的会议',
    '  · 不同主体做同类事（**「不同主体」必须是两个不同的具体对象**：不同国名 / 不同公司名 /',
    '    不同人名。「主要企业」与「大型企业」这种同义指代**不算**不同主体）：',
    '    「土耳其大使馆祝贺主权日」与「以色列大使馆祝贺主权日」',
    '  · 方向相反：「金价下跌」与「金价上涨」',
    '  · 不同地点/不同项目：「东哈萨克斯坦州建桥」与「阿斯塔纳建桥」',
    '  · 不同人物：「运动员甲夺金」与「运动员乙夺金」',
    '  · 只是同属一个话题、同一类机构、同一个州/部委 —— 话题相同不等于同一件事',
    '  · 两条讲的是同一主题但各自独立发生的不同事件',
    '',
    '拿不准就判「否」：把两条不同的新闻合成一条是**丢信息**，比留下重复更糟。',
    '',
    '只输出 JSON，不要解释。把**判为是同一件事**的编号列出来：',
    '{"same": [1, 4]}',
    '若一对都不是，输出 {"same": []}。',
    '',
    '# | 标题A || 标题B',
    ...renderPairs(pairs, items),
  ].join('\n');
}

/**
 * 版本 → 构造函数。**加新版本就往这里加一行，并同步 `JUDGE_PROMPT_VERSION`。**
 *
 * 版本历史：
 *   1 —— 2026-09-21 pair 形态上线（只有反例 + 末句「拿不准判否」）。**冻结，作对照**
 *   2 —— 2026-09-24 第一次校准：补「多家媒体换词重写同一发布」与「标题笔误」两类正例，
 *        并把「否认某报道 vs 该报道本身」加进反例。
 *        实测（az 12 对）：修好 2 对（Unibank 0.40、塞尔维亚笔误 0.72）、
 *        **回退 1 对**（中国 50 个联合项目 0.56）、「否认」那对仍未修好。
 *        已不在注册表里 —— 它的数据留在 `pv` A/B 记录中，源码不再保留。
 *   3 —— 2026-09-24 第二次校准：给「不同主体」下可操作判据 + 正例形态三；
 *        把「相反事实」检查提到判断方法第一步（见 `buildV3` 注释）
 */
export const JUDGE_PROMPTS: Record<number, (pairs: PromptPair[], items: PromptItem[]) => string> = {
  1: buildV1,
  3: buildV3,
};

/** 当前版本。改了判据正文就 +1，并往 `JUDGE_PROMPTS` 里登记。 */
export const JUDGE_PROMPT_VERSION = 3;

/**
 * 取指定版本的提示词构造器。
 *
 * 版本不存在时**抛错而不是回退到最新版** —— 静默回退会让 `pv=9` 这个手误
 * 跑出一个看起来正常的「最新版」结果，而那正是「分不清跑的是哪版」的老问题。
 * 调用方（体检接口）把它转成 400。
 */
export function promptBuilderFor(version?: number): (pairs: PromptPair[], items: PromptItem[]) => string {
  const v = version ?? JUDGE_PROMPT_VERSION;
  const fn = JUDGE_PROMPTS[v];
  if (!fn) {
    throw new Error(
      `未知的判组提示词版本 pv=${v}；可用：${Object.keys(JUDGE_PROMPTS).join(', ')}`,
    );
  }
  return fn;
}

/** 只有 1 个版本的对照集合不算对照 —— 体检接口用它给出可用版本清单 */
export function availablePromptVersions(): number[] {
  return Object.keys(JUDGE_PROMPTS).map(Number).sort((a, b) => a - b);
}

/**
 * 按当前版本构造提示词。**生产链路只用这个入口**（不传版本 = 用 `JUDGE_PROMPT_VERSION`）；
 * 传 `version` 是给体检接口的 `pv=` 参数做 A/B 用的。
 */
export function buildPairPrompt(
  pairs: PromptPair[],
  items: PromptItem[],
  version?: number,
): string {
  return promptBuilderFor(version)(pairs, items);
}
