/**
 * 内容层的确定性闸（2026-10-20）—— 用户 2026-10-18 投诉的 3 类「读者一眼能看出不对」的问题。
 *
 * ## 为什么这三条能做成**代码闸**而不是只写进提示词
 *
 * 本项目已经反复栽在同一条纪律上：**提示词里写了、模型不照做**。
 * 「750 座新教学楼」的正反例**早就在** `translate.ts:566-567` 里写着，
 * 而线上照样出现；量级换算规则**早就在** `:601`，而「12 млрд」照样被写成「12 亿」。
 * ⇒ 所以这三条一律走**确定性检出 → 拦下 → 带精确说明重试**（与量级闸同一套机制）。
 *
 * ## 三条各自为什么能判
 *
 * ① **指标类必须写出具体数值**（投诉 2）
 *   判据：标题/摘要提到指标，而**摘要+正文里一个数字都没有** ⇒ 读者拿不到任何数值。
 *   ⚠️ 数值若在正文里就放过（查的是摘要+正文，不只标题）。
 *
 * ② **量词歧义**（投诉 10）
 *   判据：数字 + 「座」+ **建筑名词** ⇒ 「750 座新教学楼」有歧义
 *   （是 750 座楼？还是 750 个学生名额？）。限定「建筑名词」是关键：
 *   「一座桥」「一座山」是正常汉语，不在表里。
 *
 * ③ **元评语**（投诉 4）
 *   判据：出现「最后一句是…」「最后一段是…」这类**对文章本身的评述**。
 *   ⚠️ 只收这一类极窄的模式 —— 「值得注意的是」「综上所述」在严肃新闻里会出现，
 *   收它们误报太高。
 *
 * ## 边界
 *
 * · **只报告，不改稿** —— 处置一律是「带修正说明重试」，**不删稿**。
 * · 三条都**只查译文侧**（原文侧没有这些问题的对应形态）。
 */

export type ContentIssueKind =
  | 'ambiguous-quantifier'
  | 'kin-unclear'
  | 'meta-comment'
  | 'mixed-script-name'
  // ★★ 2026-10-31 加（来源：用户让 ChatGPT 审 kg/uz 两批新闻的逐条意见）
  | 'numbers-out-of-order'
  | 'advertisement';

/**
 * ★★ 「N 个…中的 M 个」且 **M > N** ⇒ 必错（2026-10-31）。
 *
 * 真实样本（吉尔吉斯斯坦第 3 条，ChatGPT 核验后指出的）：
 * 标题「中吉乌道路工程电力线路迁移完成 **23 个路段中的 62 个**」
 * ⇒ 原文是「项目涉及 **62 处**电力线路，其中 **23 处**已完成迁移」⇒ **总数与完成数写颠倒了**。
 *
 * ⚠️ 判据为什么这么窄（只收这一种句型）：
 * · 必须出现「中的」这个结构 ⇒ 一般的「62 处线路、23 处已完成」**不匹配**（不误报）；
 * · 只在 **M > N** 时报 ⇒ 「10 个国家中的 3 个」这种**正确**的写法放过；
 * · 单位词表（个/处/座/条/项/家/户/人/台/辆/枚/所/间/名）⇒ 避免匹配年份或金额。
 */
const NUM_ORDER =
  /(\d[\d,，.]*)\s*(?:个|处|座|条|项|家|户|人|台|辆|枚|所|间|名)\s*[^。！？]{0,10}?中的\s*(\d[\d,，.]*)\s*(?:个|处|座|条|项|家|户|人|台|辆|枚|所|间|名)/g;

/**
 * ★★ **广告痕迹**（2026-10-31）。
 *
 * 真实样本（乌兹别克斯坦第 1 条「卡普塔尔银行提供 21% 年利率的再融资抵押贷款」）：
 * ChatGPT 核验后指出「UzNews **将其标为广告**」，且正文里有**客服电话、申请提示**等广告内容。
 *
 * ⚠️ 为什么收这几个词、且**不收**「致电」：
 * · 「致电」在正常新闻里会出现（总统致电祝贺）⇒ 收它就是误伤；
 * · 而「客服电话 / 咨询热线 / 扫码咨询 / 立即申请 / 详情请咨询」是**广告体**的强特征
 *   ⇒ 正常新闻里几乎不会出现 ⇒ 零误判风险。
 */
const AD_MARK =
  /(客服电话|客服热线|服务热线|咨询热线|客户热线|请拨打|拨打客服|扫码咨询|扫码申请|加微信|点击链接|详情请咨询|申请热线|在线申请|立即申请)/;


export interface ContentIssue {
  kind: ContentIssueKind;
  /** 命中的原文片段（给日志与修正指令用） */
  sample: string;
  /** 一句话说明「错在哪、该改成什么」 */
  detail: string;
}

/**
 * 「数字 + 座 + 建筑名词」—— 「N 座教学楼」的歧义就在这里。
 *
 * ⚠️⚠️ **只抓「N 座」，不抓「N 座位」**（2026-10-20 实测后定的）：
 * 原文 `школа на 275 мест`（= 275 个座位）译成「**275 座位**的现代化学校」是**准确的**，
 * 而「750 **座**新教学楼」是错的（少了个「位」，读者会当成 750 座楼）。
 * ⇒ 两者只差一个「位」字，而**那一个字决定了谁对** ⇒ 判据必须按它分。
 * （实测：宽一格就多 2 处误报，正好是这个形状。）
 */
const AMBIGUOUS_QUANTIFIER =
  /(\d[\d.,]*)\s*座\s*(?:的[^，。；\n]{0,6}?)?(?:新[^，。；\n]{0,4}?)?(教学楼|学校|中学|小学|幼儿园|校区|厂房|大楼|居民楼|公寓楼|体育馆|图书馆)/g;

/**
 * 「亲属词开头」⇒ 读者不知道**是谁**的亲属（用户 2026-10-20 投诉 3：
 * 「女儿向哈萨克斯坦开发银行申请 10.01 兆瓦水电站融资」——「女儿」是谁的女儿？）。
 *
 * ⚠️ 判据只取**标题以亲属关系词开头**这一种形状：
 * 「某某的女儿」是正常的（不以亲属词开头 ⇒ 放过），而「女儿向…」才是问题。
 * ⇒ 误报极低（真以「女儿」开头的新闻极少，且那类稿子本来也该写清是谁）。
 */
const KIN_FIRST_WORD =
  /^(?:女儿|儿子|母亲|父亲|妻子|丈夫|哥哥|姐姐|弟弟|妹妹|祖父|祖母|外孙|外孙女|侄子|侄女|女婿|儿媳|遗孀)/;

/**
 * **专名中英混搭**（2026-10-24）：「中文音译 + `·` + 拉丁字母」。
 *
 * ## 为什么是问题
 *
 * 项目的口径（2026-09-23 起）是「**人名/公司名/机构名保留拉丁，国名/州名/城市继续中文**」
 * ⇒ 要么**全拉丁**（`Marco Rubio`），要么**全中文**（`马科·鲁比奥`）。
 * ⇒ 而模型有时会**混搭**：「马科·**Rubio**」（用户 2026-10-24 报过：
 * 「美国国务卿鲁比奥这肯定是个约定俗成的中文翻译啊，你要不然全英文，要不然全中文，
 * 搞这个半中文半英文，就非常奇怪」）。
 *
 * ## 判据（机械、零误报）
 *
 * **一个「·」前面是汉字、后面紧跟拉丁字母** ⇒ 就是混搭。
 * ⚠️ 「·」在中文里也用于**地名词**（「塔什干·撒马尔罕」）⇒ 但那两边都是汉字 ⇒ 不匹配。
 */
const MIXED_SCRIPT_NAME = /[\u4e00-\u9fa5]\s*·\s*[A-Za-z][A-Za-z'’-]{1,}/;

/** 元评语：**只收「对文章本身的评述」这一类极窄的模式。 */
const META_COMMENT = /(最后一句(?:是|为|写的是)|最后一段(?:是|为|写的是)|上文(?:所说|提到)的)/g;

const METRIC_FIX = [
  '这类新闻**必须写出具体数值** —— 读者要的是数字，不是「有所上升」「创下新高」这种说法。',
  '请把原文里的具体数字（金额、比例、百分比、汇率点位）**直接写进摘要与正文**。',
  '例如：「国家银行确定 10 月 17 日的汇率」⇒ 要写成「……汇率：美元兑索姆 87.42，索姆兑欧元 94.17」这样。',
];

const QUANTIFIER_FIX = [
  '「N 座 + 建筑名词」这个写法**有歧义**：读者会以为那是 N 座楼，而不是 N 个人/名额。',
  '请改成**把数字修饰的名词写出来**的写法：',
  '  · 教学楼/学校/名额类 ⇒ 「可容纳 N 名学生的新教学楼」「新增 N 个学生名额」',
  '  · 场馆类 ⇒ 「可容纳 N 人的体育馆」',
];

const META_FIX = [
  '**不要在正文里写对文章本身的评述**（如「最后一句是…」「上文所说的…」）——',
  '只讲新闻本身。要交代的事实请**直接写成一句话**，不要加评述性的话头。',
];

function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * @param headText 标题 + 摘要（**不含正文**）
 * @param fullText  标题 + 摘要 + 正文（给量词/元评语用）
 *
 * ⚠️ **为什么指标类只看「标题+摘要」**（2026-10-20 实测后定的）：
 * 用户 2026-10-18 抱怨的是「一定要把具体的数值体现出来，否则没有意义」——
 * 而**读者在日报里先看到的是标题和摘要**，数字若只藏在正文末尾，等于没写。
 * 最初这一条查的是「标题+摘要+正文」，结果**一条都没命中**：
 * 那些稿子的数字都在正文里（例：「国家银行发布宏观经济预测：美元汇率、通货膨胀和石油价格」，
 * 摘要里只有指标名，数值在正文）⇒ **判据放宽等于这个投诉根本没被覆盖。**
 */
export function findContentIssues(headText: string, fullText?: string): ContentIssue[] {
  const out: ContentIssue[] = [];
  const head = headText || '';
  const text = fullText ?? head;

  // ⚠️⚠️ **「指标类必须写出具体数值」这一条**（用户 2026-10-18 投诉 2）
  // **曾经做成确定性闸，实测误报 60%+ ⇒ 已撤掉**（2026-10-20）。
  // 原因：「利率 / 通胀 / GDP / 汇率」在**政策讨论**语境里出现时**本来就不该给数值**
  // （例：「该措施可能促使部分信贷利率下降」「融资规模与期限尚未披露」
  //      「IMF 对非石油收入增长成果表示肯定」——正文提 GDP 增长但那是**结论**不是**预测值**），
  // 而「这个指标**在这里**该不该给数值」**判不准** ⇒ 机械判据做不到。
  // ⇒ 改由**提示词强化**处理（`translate.ts` 的第 7 条数字规则旁已加要求与正反例）。

  // ---- ② 量词歧义 ----
  const q = AMBIGUOUS_QUANTIFIER.exec(text);
  if (q) {
    out.push({
      kind: 'ambiguous-quantifier',
      sample: q[0].trim(),
      detail: `「${q[0].trim()}」这个量词有歧义（读者会当成 N 座楼），应当把数字修饰的名词写出来。`,
    });
  }
  AMBIGUOUS_QUANTIFIER.lastIndex = 0;

  // ---- ③ 专名中英混搭 ----
  const mixed = MIXED_SCRIPT_NAME.exec(text);
  if (mixed) {
    out.push({
      kind: 'mixed-script-name',
      sample: mixed[0].trim(),
      detail:
        `「${mixed[0].trim()}」是**中文音译 + 拉丁**混搭。` +
        `要么全用中文译名（马科·鲁比奥），要么全用拉丁原名（Marco Rubio），不要一半一半。`,
    });
  }

  // ---- ④ 亲属词开头（指代不清）----
  const kin = KIN_FIRST_WORD.exec(text.trim());
  if (kin) {
    out.push({
      kind: 'kin-unclear',
      sample: kin[0],
      detail: `标题以「${kin[0]}」开头，读者不知道**这是谁的**${kin[0]} —— 标题必须把主体写清楚。`,
    });
  }

  // ---- ④ 元评语 ----
  const m = META_COMMENT.exec(text);
  if (m) {
    out.push({
      kind: 'meta-comment',
      sample: m[0].trim(),
      detail: `「${m[0].trim()}」是对文章本身的评述，不该出现在正文里。`,
    });
  }
  META_COMMENT.lastIndex = 0;

  // ---- ★★ ⑤ 数字顺序颠倒（2026-10-31）----
  // 「23 个路段中的 62 个」⇒ 完成数 > 总数 ⇒ 必错。
  // ⚠️ 只报**确定的**颠倒（M > N）；「10 个国家中的 3 个」这种正确写法放过。
  NUM_ORDER.lastIndex = 0;
  let mo: RegExpExecArray | null;
  while ((mo = NUM_ORDER.exec(text)) !== null) {
    const total = Number(String(mo[1]).replace(/[,，.]/g, ''));
    const part = Number(String(mo[2]).replace(/[,，.]/g, ''));
    if (!Number.isFinite(total) || !Number.isFinite(part)) continue;
    if (part > total) {
      out.push({
        kind: 'numbers-out-of-order',
        sample: mo[0].trim(),
        detail:
          `「${mo[0].trim()}」的数字顺序颠倒了：稿子里写的是「${total} 个中的 ${part} 个」，` +
          `而**部分数（${part}）比总数（${total}）还大** ⇒ 必错` +
          `⇒ 请核对原文，把两个数**对调**（正确写法是「${part} 个中的 ${total} 个」）。`,
      });
      break; // 一条稿子报一次就够
    }
  }
  NUM_ORDER.lastIndex = 0;

  // ---- ★★ ⑥ 广告痕迹（2026-10-31）----
  const ad = AD_MARK.exec(text);
  if (ad) {
    out.push({
      kind: 'advertisement',
      sample: ad[0],
      detail:
        `正文里出现了「${ad[0]}」—— 这是**广告体**的特征，不是新闻事实` +
        `⇒ 若是银行/券商的产品推介稿，请整条放弃；若是新闻里的正常内容，请去掉这类招揽文字。`,
    });
  }

  return out;
}

/**
 * **机械剥离**元评语（2026-10-23）。
 *
 * ## 为什么是「剥离」而不是「拦下重试」
 *
 * 元评语（「最后一句是具体事实。」）是**一整句独立的评述**，删掉它不损失任何事实
 * ⇒ ⇒ **直接删掉最干净**：零重试、零丢稿、零误删风险。
 * ⚠️ 而「拦下重试」那条路有个致命问题：闸命中 ⇒ `ok=false` ⇒ 三次不过 ⇒ **这篇稿子不入库**
 * ⇒ **静默丢稿** —— 本项目最忌讳的形态（`translate.ts` 的 `GateReject` 注释里写着
 * 「宁可留重复，不要丢稿」）。
 *
 * ## ⚠️ 这是 2026-10-23 才发现的接线 bug（**同类问题第二次**）
 *
 * ① 我 10-20 加这道闸时，**只让它产生 `reject`，没把它接进 `ok`** ⇒
 *    `result.translated` 仍为 true ⇒ `translateNews` 里 `if (result.translated && …) return result;`
 *    **抢先命中** ⇒ **`reject` 被完全忽略** ⇒ **闸从来没生效过**。
 *    （线上那两条「12 亿→120 亿」其实**不是闸的功劳**，是模型自己改对的。）
 * ② 这次改用「剥离」⇒ **不依赖 reject 机制** ⇒ 绕开整个接线问题。
 * ⇒ ⚠️ **教训：新增质检闸必须确认它真的会让 `ok` 变 false（或走剥离），否则就是装饰。**
 *
 * ## 剥离范围（极窄）
 *
 * 只删**整句**且**匹配元评语模式**的句子。
 * ⚠️ 「值得注意的是」「综上所述」**不删** —— 那是正常新闻（真实语料里出现过）。
 */
const META_SENTENCE =
  /(^|[。！？!?\n])\s*(最后一句(?:是|为|写的是)[^。！？!?\n]*[。！？!?]?|最后一段(?:是|为|写的是)[^。！？!?\n]*[。！？!?]?|上文(?:所说|提到)的[^。！？!?\n]*[。！？!?]?)/g;

/**
 * ★★ **编辑口吻 / 元推理泄漏**（2026-10-31 加）。
 *
 * ## 起因（真实线上样本，用户 2026-10-31 让 ChatGPT 审塔吉克那批新闻）
 *
 * 原文（塔吉克斯坦「扩大了批发和零售贸易的规模」那条）：
 * ```
 * 塔吉克斯坦扩大了批发和零售贸易的规模。在这一方向上，…包括食品。
 * **这是硬事实，后面第 6、8 条都建立在它上面。**
 * ```
 *
 * ⇒ 「这是硬事实，后面第 6、8 条都建立在它上面」是**模型在跟编辑说话**
 * —— 它在解释自己的编排逻辑，**读者完全看不懂**（读者不知道「第 6、8 条」是什么）。
 * ⇒ 而 `META_SENTENCE`（原有三个形态）**完全不匹配**它 ⇒ 原样进了成品。
 *
 * ## 为什么**另起一个正则**而不是往 `META_SENTENCE` 里加
 *
 * ① 原有三个形态（「最后一句是…」「最后一段是…」「上文所说的…」）是**纯评语句**，
 *    整句都是元评语 ⇒ **行为必须一字不变**（它们有已验证的回归）。
 * ② 新形态**可能是半句事实**（「这是硬事实：项目投资 5 亿美元。」）⇒ 必须带**数字护栏**。
 *
 * ## ⚠️ 数字护栏（**宁可能留一句废话，也不能删掉一条事实**）
 *
 * 含**具体数据/单位**的句子**不按编辑口吻删** —— 那是事实，不是自言自语。
 * ⚠️ 判据与用户级技能 `llm-output-cleanup-rules` 的 `NUMERIC_FACT` / `CONCRETE_PLAN` 同源。
 */
const NUMERIC_FACT =
  /[0-9０-９][^。！？]{0,8}(?:亿美元|亿|万美元|万元|万|%|％|吨|公里|兆瓦|人次|辆|台|家|个|倍|月|年|天|小时|人|户|座|条)|20[0-9]{2}年/;
/** 中文数词拦不住（「数千个」）⇒ 再补一条「具体计划动词」。 */
const CONCRETE_PLAN = /将(?:用于|投入|建设|新建|扩建|采购|安装|开工|交付|投产|建成|完成)/;

/** 这句话里有没有「具体事实」的迹象？有 ⇒ 不许按编辑口吻删。 */
export function hasConcreteData(sentence: string): boolean {
  return NUMERIC_FACT.test(sentence) || CONCRETE_PLAN.test(sentence);
}

/**
 * 编辑口吻 / 元推理泄漏的句型（**要带具体数据的那种**）。
 *
 * ⚠️ **只收三种最确定的形态**（每加一种都要过一遍双向回归）：
 * · `这是硬事实` —— 模型给自己的内容打标签（「硬」**必需**：「这是事实」在正常报道里
 *   会出现（"事实是…"）⇒ 收它就是误杀）
 * · `前面提到` / `前面说过` / `前面所述` —— 模型在指代**上文**
 *
 * ⚠️ **不收**「值得注意的是」「综上所述」「这是事实」——
 *   前两个是正常新闻（真实语料里出现过，技能里也明确列为「不删」）。
 */
const EDITOR_VOICE =
  /(^|[。！？!?\n])\s*((?:这是(?:一个)?硬事实[，,、][^。！？!?\n]*|前面(?:提到|说过|所述)[^。！？!?\n]*|后(?:面|续)第\s*[\d、,，\s]*条[^。！？!?\n]*)[。！？!?]?)/g;

/**
 * ★ 判「这句是不是含具体数据」之前，**先把序号片段剔掉**。
 *
 * ## 为什么
 *
 * 真实样本：「这是硬事实，**后面第 6、8 条**都建立在它上面。」
 * 那句里的「6、8」是**条目序号**，**不是数据** ⇒ 而数字护栏的单位表里正好有「条」
 * ⇒ ⇒ 护栏会把它当成「含具体数据的事实句」⇒ **误伤**（第一版实测：剥不掉）。
 *
 * ⇒ 而它**确实是**元推理泄漏（读者根本不知道「第 6、8 条」是什么）⇒ 必须剥。
 *
 * ⇒ 所以护栏判定前先剔掉序号片段：
 * · 「这是硬事实，后面第 6、8 条都建立在它上面。」⇒ 剔后无数据 ⇒ **剥** ✓
 * · 「这是硬事实：项目投资额达 5 亿美元。」⇒ 无序号片段 ⇒ 含数据 ⇒ **留** ✓
 */
const SEQ_FRAGMENT = /后(?:面|续)第\s*[\d、,，\s]*条[^。！？!?\n]*/g;

/** 剥掉正文/摘要里的元评语句子。返回剥离后的文本与被删掉的句子。 */
export function stripMetaComments(text: string): { text: string; removed: string[] } {
  const removed: string[] = [];
  let out = text.replace(META_SENTENCE, (_m, p1: string, p2: string) => {
    removed.push(p2.trim());
    // 保留句末标点，避免把两句话粘在一起（"…事实。下一句" ⇒ "…事实。下一句"）
    return p1;
  });
  // ---- 编辑口吻 / 元推理泄漏（2026-10-31）----
  //
  // ⚠️ **顺序要紧**：**序号形态先跑**（豁免数字护栏），再跑带护栏的那组。
  // 真实样本：「这是硬事实，后面第 6、8 条都建立在它上面。」——
  // · 序号形态必须**句首**才匹配 ⇒ 它自己匹配不上（前面还挂着「这是硬事实，」）；
  // · 带护栏的那组能匹配整句，但护栏会因「8 条」而放过 ⇒ 整句删不掉。
  // ⇒ 先把「后面第 6、8 条都建立在它上面。」剥掉，剩下「…这是硬事实，」
  //   再由带护栏的那组剥掉（那半句不含数据 ⇒ 护栏不误伤）⇒ 整句清干净。
  // ⚠️ 带数字护栏：含具体数据/单位的句子**不删**（那是事实，不是自言自语）。
  //    ⚠️ 护栏判定前**先剔掉序号片段**（那里的数字是条目序号、不是数据 ⇒ 会误伤）。
  out = out.replace(EDITOR_VOICE, (m, p1: string, p2: string) => {
    if (hasConcreteData(p2.replace(SEQ_FRAGMENT, ''))) return m; // 留着
    removed.push(p2.trim());
    return p1;
  });
  return { text: out.replace(/[ \t]{2,}/g, ' '), removed };
}

/** 给修正指令用的成段说明（按 kind 归并，一类只讲一次）。 */
export function buildContentIssueHint(issues: ContentIssue[]): string {
  const blocks: string[] = [];
  const byKind = new Map<ContentIssueKind, ContentIssue[]>();
  for (const i of issues) {
    const arr = byKind.get(i.kind) ?? [];
    arr.push(i);
    byKind.set(i.kind, arr);
  }
  if (byKind.has('ambiguous-quantifier')) {
    const s = byKind.get('ambiguous-quantifier')!.map((i) => `  · ${i.sample}`).join('\n');
    blocks.push(
      ['⚠️ 你上一次的输出**没有通过质检**：量词有歧义。', '具体是：', s, ...QUANTIFIER_FIX].join('\n'),
    );
  }
  if (byKind.has('numbers-out-of-order')) {
    const s = byKind.get('numbers-out-of-order')!.map((i) => `  · ${i.sample}`).join('\n');
    blocks.push(
      [
        '⚠️ 你上一次的输出**没有通过质检**：数字的**总数与部分数写颠倒了**。',
        '具体是：',
        s,
        '正确写法是「**N 个中的 M 个**」，且 **M 必须小于 N**。',
        '例如原文说「项目涉及 62 处线路，其中 23 处已完成」，就应写成「62 处中的 23 处」，不能写成「23 个路段中的 62 个」。',
        '请**回到原文核对**这两个数字，然后改写。',
      ].join('\n'),
    );
  }
  if (byKind.has('advertisement')) {
    const s = byKind.get('advertisement')!.map((i) => `  · ${i.sample}`).join('\n');
    blocks.push(
      [
        '⚠️ 你上一次的输出**没有通过质检**：正文里混进了**广告体**的文字。',
        '具体是：',
        s,
        '日报只登**新闻事实**，不登招揽文字。',
        '若是银行、券商、交易所的产品推介稿（介绍利率、额度、申请方式并留客服电话），**整条不要写**；',
        '若它确实是新闻，请把这类招揽文字**全部删掉**，只留事实（主体、金额、条件、时间）。',
      ].join('\n'),
    );
  }
  if (byKind.has('kin-unclear')) {
    const s2 = byKind.get('kin-unclear')!.map((i) => `  · ${i.sample}`).join('\n');
    blocks.push(
      [
        '⚠️ 你上一次的输出**没有通过质检**：标题以亲属关系词开头，读者不知道那是**谁的**亲属。',
        '具体是：',
        s2,
        '请把主体写清楚：例如「前紧急情况部长之女 Galia Zhumanazarova 向哈萨克斯坦开发银行申请…」，',
        '或者改成不依赖亲属关系就能明白的说法（例如「Osiris Energy 公司…」）。',
      ].join('\n'),
    );
  }
  if (byKind.has('mixed-script-name')) {
    const s3 = byKind.get('mixed-script-name')!.map((i) => `  · ${i.sample}`).join('\n');
    blocks.push(
      [
        '⚠️ 你上一次的输出**专名中英混搭**了。',
        '具体是：',
        s3,
        '本项目的口径是「人名/公司名/机构名保留拉丁，国名/州名/城市继续中文」——',
        '所以一个人名要么**全用拉丁原名**（Marco Rubio），',
        '要么**全用中文译名**（马科·鲁比奥），**不许一半一半**。',
        '请把上面这些改成其中一种。',
      ].join('\n'),
    );
  }
  if (byKind.has('meta-comment')) {
    const s = byKind.get('meta-comment')!.map((i) => `  · ${i.sample}`).join('\n');
    blocks.push(
      ['⚠️ 你上一次的输出**没有通过质检**：正文里出现了对文章本身的评述。', '具体是：', s, ...META_FIX].join('\n'),
    );
  }
  return blocks.join('\n\n');
}
