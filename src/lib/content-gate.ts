/**
 * 内容层的确定性闸（2026-10-20）—— 用户 2026-10-18 投诉的 3 类「读者一眼能看出不对」的问题。
 *
 * ## 为什么这三条能做成**代码闸**而不是只写进提示词
 *
 * 本项目已经反复栽在同一条纪律上：**提示词里写了、模型不照做**。
 * 「750 座新教学楼」的正反例**早就在** `translate.ts:566-567` 里写着，
 * 而线上照样出现；量级换算规则**早就在** `:601`，而「12 млрд」照样被写成「12 亿」。
 * ⇒ 所以这三条一律走**确定性检出 → 拦下 → 带精确说明重试**（与量级闸同一套机制）。
 *
 * ## 三条各自为什么能判
 *
 * ① **指标类必须写出具体数值**（投诉 2）
 *   判据：标题/摘要提到指标，而**摘要+正文里一个数字都没有** ⇒ 读者拿不到任何数值。
 *   ⚠️ 数值若在正文里就放过（查的是摘要+正文，不只标题）。
 *
 * ② **量词歧义**（投诉 10）
 *   判据：数字 + 「座」+ **建筑名词** ⇒ 「750 座新教学楼」有歧义
 *   （是 750 座楼？还是 750 个学生名额？）。限定「建筑名词」是关键：
 *   「一座桥」「一座山」是正常汉语，不在表里。
 *
 * ③ **元评语**（投诉 4）
 *   判据：出现「最后一句是…」「最后一段是…」这类**对文章本身的评述**。
 *   ⚠️ 只收这一类极窄的模式 —— 「值得注意的是」「综上所述」在严肃新闻里会出现，
 *   收它们误报太高。
 *
 * ## 边界
 *
 * · **只报告，不改稿** —— 处置一律是「带修正说明重试」，**不删稿**。
 * · 三条都**只查译文侧**（原文侧没有这些问题的对应形态）。
 */

export type ContentIssueKind =
  | 'ambiguous-quantifier'
  | 'kin-unclear'
  | 'meta-comment';

export interface ContentIssue {
  kind: ContentIssueKind;
  /** 命中的原文片段（给日志与修正指令用） */
  sample: string;
  /** 一句话说明「错在哪、该改成什么」 */
  detail: string;
}

/**
 * 「数字 + 座 + 建筑名词」—— 「N 座教学楼」的歧义就在这里。
 *
 * ⚠️⚠️ **只抓「N 座」，不抓「N 座位」**（2026-10-20 实测后定的）：
 * 原文 `школа на 275 мест`（= 275 个座位）译成「**275 座位**的现代化学校」是**准确的**，
 * 而「750 **座**新教学楼」是错的（少了个「位」，读者会当成 750 座楼）。
 * ⇒ 两者只差一个「位」字，而**那一个字决定了谁对** ⇒ 判据必须按它分。
 * （实测：宽一格就多 2 处误报，正好是这个形状。）
 */
const AMBIGUOUS_QUANTIFIER =
  /(\d[\d.,]*)\s*座\s*(?:的[^，。；\n]{0,6}?)?(?:新[^，。；\n]{0,4}?)?(教学楼|学校|中学|小学|幼儿园|校区|厂房|大楼|居民楼|公寓楼|体育馆|图书馆)/g;

/**
 * 「亲属词开头」⇒ 读者不知道**是谁**的亲属（用户 2026-10-20 投诉 3：
 * 「女儿向哈萨克斯坦开发银行申请 10.01 兆瓦水电站融资」——「女儿」是谁的女儿？）。
 *
 * ⚠️ 判据只取**标题以亲属关系词开头**这一种形状：
 * 「某某的女儿」是正常的（不以亲属词开头 ⇒ 放过），而「女儿向…」才是问题。
 * ⇒ 误报极低（真以「女儿」开头的新闻极少，且那类稿子本来也该写清是谁）。
 */
const KIN_FIRST_WORD =
  /^(?:女儿|儿子|母亲|父亲|妻子|丈夫|哥哥|姐姐|弟弟|妹妹|祖父|祖母|外孙|外孙女|侄子|侄女|女婿|儿媳|遗孀)/;

/** 元评语：**只收「对文章本身的评述」这一类极窄的模式。 */
const META_COMMENT = /(最后一句(?:是|为|写的是)|最后一段(?:是|为|写的是)|上文(?:所说|提到)的)/g;

const METRIC_FIX = [
  '这类新闻**必须写出具体数值** —— 读者要的是数字，不是「有所上升」「创下新高」这种说法。',
  '请把原文里的具体数字（金额、比例、百分比、汇率点位）**直接写进摘要与正文**。',
  '例如：「国家银行确定 10 月 17 日的汇率」⇒ 要写成「……汇率：美元兑索姆 87.42，索姆兑欧元 94.17」这样。',
];

const QUANTIFIER_FIX = [
  '「N 座 + 建筑名词」这个写法**有歧义**：读者会以为那是 N 座楼，而不是 N 个人/名额。',
  '请改成**把数字修饰的名词写出来**的写法：',
  '  · 教学楼/学校/名额类 ⇒ 「可容纳 N 名学生的新教学楼」「新增 N 个学生名额」',
  '  · 场馆类 ⇒ 「可容纳 N 人的体育馆」',
];

const META_FIX = [
  '**不要在正文里写对文章本身的评述**（如「最后一句是…」「上文所说的…」）——',
  '只讲新闻本身。要交代的事实请**直接写成一句话**，不要加评述性的话头。',
];

function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * @param headText 标题 + 摘要（**不含正文**）
 * @param fullText  标题 + 摘要 + 正文（给量词/元评语用）
 *
 * ⚠️ **为什么指标类只看「标题+摘要」**（2026-10-20 实测后定的）：
 * 用户 2026-10-18 抱怨的是「一定要把具体的数值体现出来，否则没有意义」——
 * 而**读者在日报里先看到的是标题和摘要**，数字若只藏在正文末尾，等于没写。
 * 最初这一条查的是「标题+摘要+正文」，结果**一条都没命中**：
 * 那些稿子的数字都在正文里（例：「国家银行发布宏观经济预测：美元汇率、通货膨胀和石油价格」，
 * 摘要里只有指标名，数值在正文）⇒ **判据放宽等于这个投诉根本没被覆盖。**
 */
export function findContentIssues(headText: string, fullText?: string): ContentIssue[] {
  const out: ContentIssue[] = [];
  const head = headText || '';
  const text = fullText ?? head;

  // ⚠️⚠️ **「指标类必须写出具体数值」这一条**（用户 2026-10-18 投诉 2）
  // **曾经做成确定性闸，实测误报 60%+ ⇒ 已撤掉**（2026-10-20）。
  // 原因：「利率 / 通胀 / GDP / 汇率」在**政策讨论**语境里出现时**本来就不该给数值**
  // （例：「该措施可能促使部分信贷利率下降」「融资规模与期限尚未披露」
  //      「IMF 对非石油收入增长成果表示肯定」——正文提 GDP 增长但那是**结论**不是**预测值**），
  // 而「这个指标**在这里**该不该给数值」**判不准** ⇒ 机械判据做不到。
  // ⇒ 改由**提示词强化**处理（`translate.ts` 的第 7 条数字规则旁已加要求与正反例）。

  // ---- ② 量词歧义 ----
  const q = AMBIGUOUS_QUANTIFIER.exec(text);
  if (q) {
    out.push({
      kind: 'ambiguous-quantifier',
      sample: q[0].trim(),
      detail: `「${q[0].trim()}」这个量词有歧义（读者会当成 N 座楼），应当把数字修饰的名词写出来。`,
    });
  }
  AMBIGUOUS_QUANTIFIER.lastIndex = 0;

  // ---- ③ 亲属词开头（指代不清）----
  const kin = KIN_FIRST_WORD.exec(text.trim());
  if (kin) {
    out.push({
      kind: 'kin-unclear',
      sample: kin[0],
      detail: `标题以「${kin[0]}」开头，读者不知道**这是谁的**${kin[0]} —— 标题必须把主体写清楚。`,
    });
  }

  // ---- ④ 元评语 ----
  const m = META_COMMENT.exec(text);
  if (m) {
    out.push({
      kind: 'meta-comment',
      sample: m[0].trim(),
      detail: `「${m[0].trim()}」是对文章本身的评述，不该出现在正文里。`,
    });
  }
  META_COMMENT.lastIndex = 0;

  return out;
}

/**
 * **机械剥离**元评语（2026-10-23）。
 *
 * ## 为什么是「剥离」而不是「拦下重试」
 *
 * 元评语（「最后一句是具体事实。」）是**一整句独立的评述**，删掉它不损失任何事实
 * ⇒ ⇒ **直接删掉最干净**：零重试、零丢稿、零误删风险。
 * ⚠️ 而「拦下重试」那条路有个致命问题：闸命中 ⇒ `ok=false` ⇒ 三次不过 ⇒ **这篇稿子不入库**
 * ⇒ **静默丢稿** —— 本项目最忌讳的形态（`translate.ts` 的 `GateReject` 注释里写着
 * 「宁可留重复，不要丢稿」）。
 *
 * ## ⚠️ 这是 2026-10-23 才发现的接线 bug（**同类问题第二次**）
 *
 * ① 我 10-20 加这道闸时，**只让它产生 `reject`，没把它接进 `ok`** ⇒
 *    `result.translated` 仍为 true ⇒ `translateNews` 里 `if (result.translated && …) return result;`
 *    **抢先命中** ⇒ **`reject` 被完全忽略** ⇒ **闸从来没生效过**。
 *    （线上那两条「12 亿→120 亿」其实**不是闸的功劳**，是模型自己改对的。）
 * ② 这次改用「剥离」⇒ **不依赖 reject 机制** ⇒ 绕开整个接线问题。
 * ⇒ ⚠️ **教训：新增质检闸必须确认它真的会让 `ok` 变 false（或走剥离），否则就是装饰。**
 *
 * ## 剥离范围（极窄）
 *
 * 只删**整句**且**匹配元评语模式**的句子。
 * ⚠️ 「值得注意的是」「综上所述」**不删** —— 那是正常新闻（真实语料里出现过）。
 */
const META_SENTENCE =
  /(^|[。！？!?\n])\s*(最后一句(?:是|为|写的是)[^。！？!?\n]*[。！？!?]?|最后一段(?:是|为|写的是)[^。！？!?\n]*[。！？!?]?|上文(?:所说|提到)的[^。！？!?\n]*[。！？!?]?)/g;

/** 剥掉正文/摘要里的元评语句子。返回剥离后的文本与被删掉的句子。 */
export function stripMetaComments(text: string): { text: string; removed: string[] } {
  const removed: string[] = [];
  const out = text.replace(META_SENTENCE, (_m, p1: string, p2: string) => {
    removed.push(p2.trim());
    // 保留句末标点，避免把两句话粘在一起（"…事实。下一句" ⇒ "…事实。下一句"）
    return p1;
  });
  return { text: out.replace(/[ \t]{2,}/g, ' '), removed };
}

/** 给修正指令用的成段说明（按 kind 归并，一类只讲一次）。 */
export function buildContentIssueHint(issues: ContentIssue[]): string {
  const blocks: string[] = [];
  const byKind = new Map<ContentIssueKind, ContentIssue[]>();
  for (const i of issues) {
    const arr = byKind.get(i.kind) ?? [];
    arr.push(i);
    byKind.set(i.kind, arr);
  }
  if (byKind.has('ambiguous-quantifier')) {
    const s = byKind.get('ambiguous-quantifier')!.map((i) => `  · ${i.sample}`).join('\n');
    blocks.push(
      ['⚠️ 你上一次的输出**没有通过质检**：量词有歧义。', '具体是：', s, ...QUANTIFIER_FIX].join('\n'),
    );
  }
  if (byKind.has('kin-unclear')) {
    const s2 = byKind.get('kin-unclear')!.map((i) => `  · ${i.sample}`).join('\n');
    blocks.push(
      [
        '⚠️ 你上一次的输出**没有通过质检**：标题以亲属关系词开头，读者不知道那是**谁的**亲属。',
        '具体是：',
        s2,
        '请把主体写清楚：例如「前紧急情况部长之女 Galia Zhumanazarova 向哈萨克斯坦开发银行申请…」，',
        '或者改成不依赖亲属关系就能明白的说法（例如「Osiris Energy 公司…」）。',
      ].join('\n'),
    );
  }
  if (byKind.has('meta-comment')) {
    const s = byKind.get('meta-comment')!.map((i) => `  · ${i.sample}`).join('\n');
    blocks.push(
      ['⚠️ 你上一次的输出**没有通过质检**：正文里出现了对文章本身的评述。', '具体是：', s, ...META_FIX].join('\n'),
    );
  }
  return blocks.join('\n\n');
}
