/**
 * 「把库内身份去重提到翻译之前」这条优化的**开关**与**窗口算术**（2026-10-10 加）。
 *
 * 这个模块刻意只有纯函数，不 import 数据库、不 import 网络：
 * 整条优化的正确性就靠两条可以单独验算的命题——
 *   ① 开关**默认关**（否则没有可比基线）；
 *   ② 前置探测用的窗口必须**严格窄于**闸 2 的窗口（否则会丢稿，见下）。
 * 把它们做成纯函数，`scripts/test-dedup-before-translate.ts` 就能直接断言，
 * 不必拉起一轮真实抓取（一轮两小时，且要花钱）。
 *
 * ## 为什么值得做（这是**实测数**，不是估计）
 *
 * 线上 2026-09-24 19:00 那轮的读数（见 `AGENTS.md`）：`saved = 295`、
 * **`dedup.againstDb = 85`**。`againstDb` 是**被闸 2 丢掉**的条数，而闸 2 跑在
 * 翻译循环**之后** ⇒ 这 85 篇是**先翻译、再丢掉**的。按实测 37 秒/篇
 * （`scheduler.ts` 的 `MEASURED_WORST_PER_ARTICLE_MS`）算 ≈ **52 分钟/轮**，
 * 外加 85 篇的翻译费。而它们是不是重复，在翻译**之前**就已经完全可知 ——
 * 判据只用 `item.link` 与 `original_title` 两个翻译前字段。
 *
 * ## 为什么这不改变输出集合（正确性依据，别删）
 *
 * 记 `S` = 本轮候选里「身份命中库内窗口」的那些。闸 2 丢一条稿子当且仅当它在 `S` 里。
 * 库内窗口存的就是 `canonicalUrl(source_url)` / `originalTitleKey(original_title)`
 * （见 `db-articles.ts` 的两个查询），与本文件调用方用的**同一套归一化函数** ⇒
 * 若 A ∈ S，则**任何**与 A 同身份（同链接或同原文标题）的 B 也 ∈ S。
 * 于是：
 *   · 「提前丢掉 A」不会让任何 B 侥幸活下来——B 本来就被闸 2 丢掉；
 *   · 「闸 1（批内）少看见 A」也不会改变闸 1 的结论——会出现「先出现的 A 被提前丢掉、
 *     后出现的 B 本该被闸 1 丢掉」这种配对，要求 A ∈ S 而 B ∉ S，
 *     但同身份 ⇒ B ∈ S ⇒ 矛盾，**这种配对不存在**。
 * ⇒ 输出集合逐条相同，差别只是 S 里那些稿子不再被翻译。
 *
 * ## 失败模式：只可能是「没省下钱」，不可能是「丢稿」
 *
 * 探测查询失败 ⇒ 调用方把 `preKnownOk` 置 false ⇒ **一条都不提前跳过**，
 * 全部照旧翻译，最后由**第三步那个原封未动的闸 2** fail-closed 决定不入库。
 * 这是刻意的分工：前置探测只是**优化**，正确性永远由闸 2 承担。
 */

/**
 * `DEDUP_BEFORE_TRANSLATE` 是否打开。**默认关**：只有显式 `1` / `on` / `true` 才开。
 *
 * ⚠️ 「默认关」是刻意的，与 `SAME_EVENT_JUDGE` 的「默认开」相反：
 * 这条优化要能跟「不优化」做同条件对比（`durationMs`、
 * `dedup.skippedBeforeTranslate` 与 `dedup.againstDb` 的此消彼长），
 * 一上来默认开就没有可比基线了。
 */
export function isDedupBeforeTranslateEnabled(raw = process.env.DEDUP_BEFORE_TRANSLATE): boolean {
  const v = (raw || '').trim().toLowerCase();
  return v === '1' || v === 'on' || v === 'true';
}

/**
 * 翻译前探测可以用的窗口长度（天）；返回 `null` 表示**这个配置下不存在安全的更窄窗口**
 * ⇒ 调用方必须整条关掉这个优化（而不是悄悄退化成等宽）。
 *
 * ## 为什么必须比闸 2 的窗口窄一整天
 *
 * 前置探测跑在循环**之前**，闸 2 的查询跑在循环**之后**，两边算
 * `since = now - N 天` 用的 `now` 不同。记循环开始 `T0`、结束 `T1`（`T1 > T0`），则
 *   前置窗口 = `[T0 - p, ∞)`，闸 2 窗口 = `[T1 - d, ∞)`。
 * 要保证「前置丢掉的集合 ⊆ 闸 2 会丢的集合」（见文件头的证明，这是它的前提），
 * 需要 `T0 - p ≥ T1 - d`，即 `p ≤ d - (T1 - T0)`。
 * 一轮耗时上限是 `FETCH_HARD_WAIT_MS = 400 分钟`，所以取 `p = d - 1 天` 恒成立
 * （`d - 1 天` 远小于 `d - 400 分钟`）。
 *
 * ⚠️ **反过来（两处都用 `d`）会真的丢稿**：此时前置窗口**比**闸 2 窗口更宽，
 * `published_at` 恰好落在最老那一小段（长度 = 本轮耗时）里的行**只**出现在前置集合里
 * ⇒ 与它同身份的本轮候选会被提前丢掉，**而闸 2 本来会放行它**。
 * 这个差集很窄，所以它不会天天出事——只会偶尔、静默地少一篇，
 * **而这正是最难查的一类错**。所以宁可先收窄一天。
 *
 * `d < 2` 时收不出更窄的正整数窗口 ⇒ 返回 `null`（调用方关掉），
 * 而不是悄悄退化成 `p = d`。
 */
export function dedupPreWindowDays(dbWindowDays: number): number | null {
  if (!Number.isFinite(dbWindowDays) || dbWindowDays < 2) return null;
  return dbWindowDays - 1;
}
