/** 拿到译文的机构译名里，哪些**不是**某个缩写对应的（用于矛盾检测）。 */
export function orgNamesExcept(abbr: string): string[] {
  const out: string[] = [];
  for (const [a, name] of Object.entries(ORG_ABBREV)) {
    if (a === abbr) continue;
    if (a.endsWith('_' + abbr) || a.startsWith(abbr + '_')) continue; // 同一家机构的别名
    out.push(name);
  }
  return out;
}
