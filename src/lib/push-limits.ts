/**
 * 推送端的**产品限额**（不是判据、不是阈值 —— 是「每份报告要几条」这种取舍）。
 *
 * ## 为什么单独一个文件
 *
 * 这个常量**两个地方要用**：
 *   1. `src/app/api/wechat/push/route.ts` —— 真正截取选稿；
 *   2. `scripts/diagnose-push-window.ts` —— 回放窗口时按同一上限算「本会推几条」。
 *
 * 在 2026-10-10 之前它是**手抄两份**的，那句注释写的是
 * 「与 `POST /api/wechat/push` 的 `maxPerCountry` 一致 —— 改一处要改两处，这里是刻意的重复」。
 * 那种写法一定会分叉：改的人只要漏掉第二处，**诊断脚本就会按旧上限给出一个看起来正常的结论**，
 * 而且**不会报任何错**（正是本项目反复吃亏的「静默不一致」形态 —— 同类的还有
 * `scheduledWindow` 的手写白名单、`analyze-pair-recall` 的手抄窗口标签，都在同一次重构里被消掉）。
 *
 * 为什么不直接把常量留在 route 里、让脚本去 import route：
 * 路由模块会连带求值 `next/server`、`node-cron` 等一堆模块级依赖，
 * 让一个离线脚本为了拿一个数字去加载半条推送链路 —— 这正是 `publish-schedule.ts`
 * 头部注释里记着的那个坑（当年从 route 反过来 import，把 `node-cron`
 * 打进了体检接口的 bundle）。**纯常量放 lib，两边都 import，是唯一不留分叉余地的写法。**
 *
 * ## 📌 改了这里会发生什么
 *
 * - 线上 `GET /api/wechat/push` 的 `codeVersion.pushMaxPerCountry` **自动跟着变**
 *   ⇒ 部署完一条 curl 就能确认新值接管了没有（不用等一轮跑完去数草稿）。
 * - `scripts/diagnose-push-window.ts` 的回放结论自动跟上，不会和线上脱钩。
 */

/**
 * 每国每份报告的篇数上限 —— **产品旋钮**，改它之前请读完整段。
 *
 * ### 变更史（必须留痕：本项目栽过「没人知道为什么是 15」的跟头）
 *
 * | 时期 | 值 | 理由 |
 * |---|---|---|
 * | ≤2026-09-22 | 30 | —— |
 * | 2026-09-22 | **15** | 当时是**早晚报两段**（各 12h，见 `publish-schedule.ts`）。每份报告每国 15 篇已经足够，30 篇只会把相关性靠后的稿子也塞进来、拉低整份报告的质量。 |
 * | **2026-10-10** | **20** | 早晚报合并成**一天一份日报**后，每国一天只出一次报告 —— 原来分散在两轮里的量现在挤进一轮，15 偏薄。用户原话：「合并后的日报，没必要每天推送 30 条，比原来单个 15 个多一些，比如 20 即可」⇒ **不要回到 30**，停在 20。 |
 *
 * ### ⚠️ 这是**上限**，不是配额
 *
 * 候选不足时按实际可用量推，**不硬凑**。这条纪律比数字本身重要 ——
 * 硬凑就得放宽判据，而本项目历史上「判据过严 / 过松」都出过事。
 * 用户 2026-10-10 也把这条点出来了：
 * 「没有那么多新闻，达不到也没关系，但是千万不要重复，不要搞没用的新闻」。
 *
 * ### ⚠️ 调大它会让「每国不足 N 篇」这个症状更难出现（不是消失）
 *
 * 候选不足时先用 `GET /api/fetch-news` 的 `funnelByCountry` 看漏斗掉在哪一段，
 * **不要去动 `pushExclusionReason` 或这个常量**。
 *
 * ### ⚠️⚠️ 它和总审的**删稿额度**是一对（2026-10-10 记下这个耦合）
 *
 * 每国条数变多 ⇒ 单国里「模型想删的重复/无效条」也更容易变多，
 * 而总审的删除额度是 `min(MAX_DROPS=4, floor(n/3))` —— n 从 15 到 20 都还是 **4**。
 * 额度不够时的失败方式是**整组作废**（不是截断取前 4 条）：`dropSet.clear()` ⇒
 * **一条都不删**，重复原样留在成品里。这正是用户最在意的那个观感。
 * ⇒ 所以 `push/route.ts` 在阶段 ② 之后有一条**专门的 `console.warn`** 盯这件事
 * （形如「⚠️ 总审删稿额度不足，整组作废」）。若它开始频繁出现，
 * 要动的是 `MAX_DROPS`（**先量后调，别拍**），不是去放宽别的判据。
 *
 * ### 📌 它有可能是个 **no-op**
 *
 * 这个上限只在「过完判据 + 去重后的候选数 > 20」时才起作用。
 * 2026-10-10 实测 5 国 24h 窗口的**原始行数**：az 53 / kg 27 / kz 26 / uz 15 / tj 12（合计 133）；
 * 过完判据后逐国还剩多少**当天读不到**（`lastRun.summary` 是内存态，被滚动发布清空了）。
 * ⇒ 下一轮跑完去看 `summary`：若逐国 `eligible` 普遍 < 20，说明真正卡住产量的是
 * **候选量**而不是这个上限，再调大它也不会多推一条 —— 该动的是上游的信息源。
 */
export const PUSH_MAX_PER_COUNTRY = 20;

/**
 * ★ **每国进「同一件事」判组的候选上限**（2026-10-28 加）。
 *
 * ## 为什么必须有这个（**这是「草稿箱只有 2 篇」的根因**）
 *
 * 2026-10-28 上午：草稿箱里只有哈萨克、乌兹别克两国的稿子，
 * 吉尔吉斯/塔吉克/阿塞拜疆三国的草稿**整轮没出来**。
 *
 * ⇒ 根因链（**不是超时、不是部署、不是窗口**）：
 * ① 选稿时 `eligible` = **本国全部合格候选**，**没有上限**
 *    ⇒ 2026-10-27 那一轮入库 433 篇（kz 一国就 165 篇）；
 * ② `dedupeStories(eligible)` 内部要**两两配对**算相似度 ⇒ **O(n²)**
 *    ⇒ 165 篇 ⇒ 约 **1.35 万次** bigram 集合运算；
 * ③ 而容器规格是 **0.25 核 / 0.5 G**（2026-10-28 用户截图确认）⇒ ⇒ 这套计算**极慢**；
 * ④ ⇒ 整轮在逐国发布的**中途**崩掉 ⇒ ⇒ **前两国的草稿已建（不可回滚），后三国没轮到**
 *    ⇒ ⇒ 崩在**第 3 国** ⇒ 用户的现象与它**完全吻合**。
 *
 * ## 修法
 *
 * **在判组之前**按投资相关性截断候选（`scoredArticles` 已按
 * `compareByInvestmentRelevance` 排好序 ⇒ 截掉的是**相关性最低的尾部**）。
 * ⇒ ⇒ 判组的输入量**恒定** ⇒ ⇒ 不会再因某天稿件一多就崩。
 *
 * ## 取 60 的理由
 *
 * · 配对数从约 1.35 万降到约 1770（**-87%**）；
 * · `PUSH_MAX_PER_COUNTRY` 是 20（出稿上限）⇒ 60 条候选去重后仍远够 20 条；
 * · 越靠前越相关 ⇒ **被截掉的尾部相关性最低**。
 *
 * ## ⚠️ **不许静默截断**
 *
 * 截掉的条数**必须报出来**（`summary.candidatesDroppedByLimit`，
 * `stage: 'before_judge'`）—— 否则「为什么这期只有 12 篇」会变成查不到依据的谜题。
 */
export const PUSH_JUDGE_CANDIDATE_CAP = 60;
