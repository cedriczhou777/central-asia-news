/**
 * 跑一遍全部活体探针，返回**字符串**（不是布尔）。
 *
 * 为什么一律返回字符串：一个 `true` 只能说明「这段代码存在」，
 * 说明不了「它做对了」。字符串能一眼看出「量到了多少、是哪个判据拦的」。
 *
 * ⚠️ `order` 必须给**完整排列**：不给的话 `applyVerdict` 会正常地记一条
 * 「order 缺失或不是数组 ⇒ 保持原序」，于是期望值「删了 1 条｜无拒绝记录」永远不成立。
 */
export function runEditorProbes(): Record<string, string> {
  // ① order 示例的形状（v3）：模板写成 `"order": [{ORDER_EXAMPLE}]` 会渲染出 `[[0, 1, 2]]`，
  //    模型照抄 ⇒ 排序全部作废，而报错看起来像「模型没给」。
  const orderExample = (() => {
    const p = buildEditorPrompt({ countryName: '探针', items: EDITOR_PROBE_ITEMS });
    const m = p.match(/"order":\s*(\[[^\]\n]*\])/);
    return m ? m[1] : '(没匹配到)';
  })();

  // ② 抄示例的那句空话删不掉稿（v3）。
  //    ⚠️ kind 必须是 `not_news`：v4 把证据按 kind 分型后，同一条理由走 `duplicate`
  //    会**先**撞上「没给出有效 sameAs」，于是这条探针就改测了另一道闸 ——
  //    它仍然返回「删了 0 条」，**看起来一切正常**，但它声称在守的引文闸已经没人盯着了。
  //    `not_news` 没有可指认的字段，引文是它唯一的证据 ⇒ 这条探针才真的落在引文闸上。
  const dropGuard = (() => {
    const r = applyVerdict(EDITOR_PROBE_ITEMS, {
      drops: [
        {
          index: 1,
          kind: 'not_news',
          reason: '与第 2 条同为 9 月 27 日阿塞拜疆政府与 AIIB 的那场会谈',
        },
      ],
    });
    return `删了 ${r.audit.appliedDrops} 条｜${r.audit.rejections[0] ?? '没有拒绝记录（护栏可能失效了）'}`.slice(0, 140);
  })();

  // ③ 原文有没有真的进到提示词（v4 全部效力的开关）。
  const original = (() => {
    const p = buildEditorPrompt({ countryName: '探针', items: EDITOR_PROBE_ITEMS });
    // 「截断标记」单独造一条**超长摘录**来验：`EDITOR_PROBE_ITEMS` 的假原文本来就很短
    // （**理应不截断**），拿它去测「有没有留下省略号」永远是「否」——
    // 那是一个测不出东西的格子（第一版就是这么写的）。
    const over = ORIGINAL_EXCERPT_MAX + 1;
    const pLong = buildEditorPrompt({
      countryName: '探针',
      items: [{ ...EDITOR_PROBE_ITEMS[0], originalExcerpt: 'X'.repeat(over) }],
    });
    return [
      `原文标题=${p.includes('PROBE ORIGINAL TITLE 0') ? '是' : '否'}`,
      `原文正文=${p.includes('PROBE ORIGINAL BODY 0') ? '是' : '否'}`,
      `语言=${p.includes('[xx]') ? '是' : '否'}`,
      `截断标记=${pLong.includes('（已截断）') ? '是' : '否'}`,
      `超长被截=${pLong.includes('X'.repeat(over)) ? '否（没截断）' : '是'}`,
    ].join(' ');
  })();

  // ④ v3 那个把模型正确判断拦掉的引文闸，现在放行了吗（duplicate 只认 sameAs）。
  const dupEvidence = (() => {
    const n = EDITOR_EVIDENCE_PROBE_ITEMS.length;
    const r = applyVerdict(EDITOR_EVIDENCE_PROBE_ITEMS, {
      order: Array.from({ length: n }, (_, i) => i),
      drops: [
        { index: 1, kind: 'duplicate', sameAs: 0, reason: '与第 0 条是同一件事的两家报道（无引文，靠 sameAs 作证）' },
      ],
    });
    // 样本不够时先把「探针自己坏了」说出来 —— 否则这一格会被读成「护栏坏了」
    const note = probeDropBudgetOk(n) ? '' : `（⚠️ 样本只有 ${n} 条，删 1 条过不了上限/保留下限 ⇒ 本探针无效）`;
    return `删了 ${r.audit.appliedDrops} 条｜${r.audit.rejections[0] ?? '无拒绝记录'}${note}`.slice(0, 140);
  })();

  // ⑤ 反向证明引文闸没有被一起放开。
  const notNewsQuote = (() => {
    const n = EDITOR_EVIDENCE_PROBE_ITEMS.length;
    const r = applyVerdict(EDITOR_EVIDENCE_PROBE_ITEMS, {
      order: Array.from({ length: n }, (_, i) => i),
      drops: [{ index: 1, kind: 'not_news', reason: '这一条不是新闻（故意不引用原文，应当被拒）' }],
    });
    return `删了 ${r.audit.appliedDrops} 条｜${r.audit.rejections[0] ?? '无拒绝记录（引文闸可能失效了）'}`.slice(0, 140);
  })();

  // ⑥ g2「改字定位闸」的**双向**活体探针（2026-10-04 新增）。
  //
  // 为什么必须双向：g1 的教训就是「只证明了**没放过错的**、没证明**没丢掉对的**」。
  // 所以这一格一次报两条**都取自 10-04 线上真实被拒记录**的用例：
  //   · A（幻觉）az `fixes[4]`：它的 `before` 是**另一条**的标题 ⇒ 必须拒，且点名第 1 条；
  //   · B（走样）tj `fixes[5]`：它的 `before` 中间漏了「完成」二字 ⇒ 必须采纳。
  // 两格都对，才说明这一版**既有放宽、又没把幻觉放进来** —— 只看一格的话，
  // 一个「什么都不拒」的坏闸和一个「什么都不放」的死闸都能显示成正常。
  const fixLocate = (() => {
    const azRows = [
      '阿塞拜疆混凝土结构产量增长3.4倍，沥青产量下降',
      '“OPEC+ 阿塞拜疆等七国讨论世界石油市场形势及履行产量承诺”',
    ];
    const a = locateFixTarget(azRows[1], 0, azRows);
    const tj = locateFixTarget(
      '塔吉克斯坦政府计划在 2026 年播种 611,772 公顷，截至 10 月 25 日已播种 116,648 公顷，完成',
      0,
      ['塔吉克斯坦政府计划在 2026 年播种 611,772 公顷，截至 10 月 25 日已完成 116,648 公顷，完成率为 19.2%。这也'],
    );
    return (
      `A:${a.ok ? '❗采纳了（幻觉没挡住）' : `拒绝·指第${a.pointsAt}条`} ` +
      `B:${tj.ok ? `采纳(${tj.how})` : '❗拒绝（走样没捞回来）'}`
    );
  })();

  return {
    editorOrderExampleProbe: orderExample,
    editorDropGuardProbe: dropGuard,
    editorOriginalProbe: original,
    editorDupEvidenceProbe: dupEvidence,
    editorNotNewsQuoteProbe: notNewsQuote,
    editorFixLocateGateProbe: fixLocate,
  };
}

/**
 * 跨国「同一件事」的**确定性**观测（只报不改）。
 *
 * 为什么不据此删：`AGENTS.md` 已经写明「跨国出现同一件事是**预期行为**，不是重复」——
 * 同一个事件在哈萨克斯塔篇和乌兹别克斯坦篇里各出现一次，是两国读者各自需要的。
 * 所以这里只做两件事：喂给模型当**知情上下文**（并要求它不要据此删），
 * 以及写进本轮审计（用户若想知道「这条是不是两个国家都推了」，有地方可查）。
 *
 * 阈值 0.4：远低于 `isSameTitle` 的 0.95 —— 这是**观测**不是判据，
 * 宁可多报几条让人看，也不要漏掉。
 *
 * ⚠️ 这个 0.4 是**量出来的**，不是拍的。真实的阿塞拜疆重复对
 * （`APA`「阿塞拜疆与亚洲基础设施投资银行就基础设施项目合作进行讨论」
 * ←→ `Trend.az`「阿塞拜疆与亚洲基础设施投资银行讨论扩大在绿色经济转型方面的合作」）
 * 实测 `similarity = 0.4595`。我最初把阈值定在 0.5，结果**这对真实锚点直接被漏掉** ——
 * 也就是说这个「观测」在最该起作用的那条上恰好是瞎的。
 *
 * 代价可控：上游 `renderOtherCountries` 已经 `slice(0, 10)` 截断，
 * 所以调低阈值最多多出几行提示词，不会灌爆。漏报的代价则是「用户问『这条是不是两国都推了』时查不到」。
 */
export function crossCountryOverlaps(
  current: ReviewItem[],
  others: Array<{ country: string; items: ReviewItem[] }>,
  minSim = 0.4,
): Array<{ withCountry: string; title: string; otherTitle: string; sim: number }> {
  const out: Array<{ withCountry: string; title: string; otherTitle: string; sim: number }> = [];
  for (const other of others) {
    for (const a of current) {
      for (const b of other.items) {
        const s = similarity(a.title, b.title);
        if (s >= minSim) {
          out.push({ withCountry: other.country, title: a.title, otherTitle: b.title, sim: s });
        }
      }
    }
  }
  return out.sort((a, b) => b.sim - a.sim);
}

// ----- 借图（2026-09-29：「重要新闻要配图」，用户选定「只挪真图」）-----

/** 一次「借图」：把已删掉的重复稿的封面挪给一条没图的幸存稿。 */
export interface CoverBorrow {
  /** 幸存稿在**最终顺序**里的下标（重排之后的下标，路由据此插图） */
  targetIndex: number;
  /** 出图的稿子标题（它已被总审删掉，不在成品里） */
  fromTitle: string;
  imageUrl: string;
  /** 两条标题的相似度 —— 用来事后回答「凭什么认为它们是一件事」 */
  sim: number;
}

/**
 * 计划「借图」：给没图的幸存稿，从**刚被删掉的重复稿**身上把封面挪过来。
 *
 * ## 为什么捐赠者只能是「已被删掉的重复稿」
 *
 * 用户对这个功能的原话是**「只挪真图」**（另一个选项是去图库搜一张，被否了）。
 * 而「真图」有一个前提：**它必须是这条新闻的照片**。这就要求两条稿子
 * 讲的**是同一件事**。三条自我约束由此而来：
 *
 * 1. **必须有一条「同一件事」的既成判断。** 凭空按相似度配对会把
 *    「同一主题的不同场会议」的图挪过来 —— 那是**事实错误**，比没图严重得多。
 *    这里唯一的既成判断就是「总审把它作为 duplicate 删掉了」（模型看过两边文字、给了理由）。
 * 2. **捐赠者必须不在成品里。** 否则同一个国家的同一天里会**两条稿子同一张图**，
 *    看起来就是重复 —— 正是用户反复在报的那个观感问题。
 *    捐赠者是**被删掉**的稿子，所以这条天然成立。
 * 3. **只挪封面，不动正文，绝不生成图、绝不搜图库。**（`article-format.ts` 现在
 *    正是把 unsplash/picsum 当**编造图**在拦。）
 *
 * ## 阈值用的是 {@link COVER_BORROW_MIN_SIM}（0.35），**不是**召回下限
 *
 * 配对用 `similarity(标题)`，下限取 0.35 —— 与 `same-event` 注释里那批
 * **已被真实语料回测过**的锚点同源（人名音译差异 0.37 / 数字有出入 0.43）。
 *
 * ⚠️ **2026-10-05 起它不再复用 `PAIR_CANDIDATE_MIN_SIM`**：那个常量降到了 0.20
 * （召回侧只要「值得问一下」，模型还会判否），而借图**没有第二道闸** ——
 * 松到 0.20 就等于「标题有两成像就把图挪过去」。理由写在 `COVER_BORROW_MIN_SIM` 上。
 *
 * ⚠️ 这条纪律来自 2026-09-29 的教训：`crossCountryOverlaps` 的阈值当初拍了个 0.5，
 * 恰好把唯一那条真实锚点（0.4595）漏掉。**阈值不能拍，也不能跨职责复用。**
 *
 * ## 为什么**不**做跨国（实测过，不是省事）
 *
 * 2026-09-29 拿线上 3 天 1152 篇量过：187 篇完全没图，其中
 * **同国能找到「同一件事且有图」的 35 篇，而「仅跨国」才多 2 篇（1%）**。
 * 为 1% 去引入一条跨国路径（还要为它单独定阈值、单独处理「同一张图出现在两国日报」的观感）
 * 不划算。要接跨国的话，先拿这个测量脚本重新量一遍再说。
 */
export function planCoverBorrows(args: {
  /** 最终成品，**顺序即最终顺序**（`targetIndex` 就是这个数组的下标） */
  survivors: Array<{ title: string; hasImage: boolean }>;
  /** 被总审删掉的重复稿里、**自己有图**的那些 */
  donors: Array<{ title: string; imageUrl: string }>;
  minSim?: number;
}): CoverBorrow[] {
  const minSim = args.minSim ?? COVER_BORROW_MIN_SIM;
  const taken = new Set<number>();
  const out: CoverBorrow[] = [];

  for (const donor of args.donors) {
    // 没标题就没法证明它和谁是一件事 ⇒ 不挪（宁可不挪，也不挪错）
    if (!donor.title || !donor.imageUrl) continue;

    let best: { index: number; sim: number } | null = null;
    for (let i = 0; i < args.survivors.length; i++) {
      const s = args.survivors[i];
      // 已经有图的不用挪；已经被别的捐赠者挪过的也不重复挪
      if (s.hasImage || taken.has(i) || !s.title) continue;
      const sim = similarity(donor.title, s.title);
      if (sim < minSim) continue;
      if (!best || sim > best.sim) best = { index: i, sim };
    }

    if (best) {
      taken.add(best.index);
      out.push({
        targetIndex: best.index,
        fromTitle: donor.title,
        imageUrl: donor.imageUrl,
        sim: best.sim,
      });
    }
  }

  return out;
}

/** 模型调用出口（与 `same-event.AskFn` 同形）。注入只为测试。 */
export type ReviewAskFn = (
  prompt: string,
) => Promise<{ ok: true; text: string; provider?: string } | { ok: false; error: string }>;

/**
 * 审一国的一篇草稿。**失败一律无损**（不改任何东西，只记 audit）。
 *
 * `temperature` 用 0：这是判定类任务，同一份输入两次跑出不同顺序/删法的话，
 * 这些「合并」「改字」的动作就没法信任（同 `JUDGE_TEMPERATURE` 的理由）。
 */
export async function reviewDraft(args: {
  countryName: string;
  items: ReviewItem[];
  overlaps?: Array<{ withCountry: string; title: string; otherTitle: string; sim: number }>;
  ask?: ReviewAskFn;
}): Promise<{ decision: ReviewDecision; audit: ReviewAudit }> {
  const n = args.items.length;
  const identity = (): ReviewDecision => ({
    finalIndices: Array.from({ length: n }, (_, i) => i),
    drops: [],
    fixes: [],
    needsImage: [],
    thinSource: [],
    verdict: '',
  });

  if (n < 2) {
    return {
      decision: identity(),
      audit: {
        promptVersion: EDITOR_PROMPT_VERSION,
        ran: false,
        ok: true,
        itemCount: n,
        rejections: ['稿件少于 2 条，没有可审的内容'],
      },
    };
  }

  const prompt = buildEditorPrompt({
    countryName: args.countryName,
    items: args.items,
    ...(args.overlaps ? { overlaps: args.overlaps } : {}),
  });
  const ask: ReviewAskFn = args.ask ?? ((p) => askLlmJson(p, { temperature: 0 }));
  const res = await ask(prompt);

  if (!res.ok) {
    return {
      decision: identity(),
      audit: {
        promptVersion: EDITOR_PROMPT_VERSION,
        ran: true,
        ok: false,
        error: res.error,
        itemCount: n,
        rejections: ['模型调用失败 ⇒ 一条都没改'],
      },
    };
  }

  const parsed = parseVerdict(res.text);
  if (!parsed) {
    return {
      decision: identity(),
      audit: {
        promptVersion: EDITOR_PROMPT_VERSION,
        ran: true,
        ok: false,
        ...(res.provider ? { provider: res.provider } : {}),
        error: '返回不是合法 JSON',
        itemCount: n,
        rejections: ['返回不是合法 JSON ⇒ 一条都没改'],
      },
    };
  }

  const { decision, audit } = applyVerdict(args.items, parsed);
  if (res.provider) audit.provider = res.provider;
  return { decision, audit };
}
