export function getArticles(filters?: {
  country?: string;
  category?: string;
  featured?: boolean;
}): NewsArticle[] {
  let result = [...mockArticles];
  if (filters?.country) {
    result = result.filter((a) => a.country === filters.country);
  }
  if (filters?.category) {
    result = result.filter((a) => a.category === filters.category);
  }
  if (filters?.featured) {
    result = result.filter((a) => a.isFeatured);
  }
  return result.sort(
    (a, b) =>
      new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()
  );
}

export function getArticleById(id: string): NewsArticle | undefined {
  return mockArticles.find((a) => a.id === id);
}

export function getFeaturedArticles(): NewsArticle[] {
  return getArticles({ featured: true });
}

export function getArticlesByCountry(countryCode: string): NewsArticle[] {
  return getArticles({ country: countryCode });
}
